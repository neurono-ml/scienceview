//! Serializing the document to SVG text.

use super::SVSvgDocument;
use crate::serialize::sv_escape_text;
use crate::serialize::sv_format_number;

/// Serializes a document to SVG text.
///
/// The attribute order of the root element and of the metadata children is
/// fixed; repeating the call on the same document always yields the same
/// bytes.
pub(super) fn sv_serialize_document(source: &SVSvgDocument) -> String {
    let width = sv_format_number(source.viewport.width());
    let height = sv_format_number(source.viewport.height());
    let label = sv_escape_text(source.accessibility_label());
    let mut svg = String::new();

    svg.push_str("<svg xmlns=\"http://www.w3.org/2000/svg\"");
    svg.push_str(" width=\"");
    svg.push_str(&width);
    svg.push_str("\" height=\"");
    svg.push_str(&height);
    svg.push_str("\" viewBox=\"0 0 ");
    svg.push_str(&width);
    svg.push(' ');
    svg.push_str(&height);
    svg.push_str("\" role=\"img\" aria-label=\"");
    svg.push_str(&label);
    svg.push_str("\">\n");

    let title = source.title.as_deref().unwrap_or("scienceview figure");
    svg.push_str("  <title>");
    svg.push_str(&sv_escape_text(title));
    svg.push_str("</title>\n");
    svg.push_str("  <desc>");
    svg.push_str(&sv_escape_text(
        source
            .description
            .as_deref()
            .unwrap_or("Figure generated by scienceview"),
    ));
    svg.push_str("</desc>\n");

    if let Some(background) = source.background {
        svg.push_str("  <rect x=\"0\" y=\"0\" width=\"");
        svg.push_str(&width);
        svg.push_str("\" height=\"");
        svg.push_str(&height);
        svg.push_str("\" fill=\"");
        svg.push_str(&background.to_hex_string());
        svg.push_str("\"/>\n");
    }

    for element in &source.elements {
        svg.push_str("  ");
        svg.push_str(element);
        svg.push('\n');
    }

    svg.push_str("</svg>\n");
    svg
}
