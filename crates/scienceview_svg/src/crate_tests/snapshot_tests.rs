//! The golden document: one exact expected string, committed with the code.
//!
//! A snapshot test is the executable form of "the documentation figures cannot
//! drift": if an attribute order or a number changes, this string changes with
//! it and the reviewer sees the diff.

use crate::document::SVSvgDocument;
use scienceview_core::sv_decoration::{SVDecorationPrimitive, SVPoint, SVStroke};
use scienceview_core::sv_layout::SVViewport;
use scienceview_core::sv_mark::{
    SVGeometryCircle, SVMarkPaint, SVMarkPoint, SVMarkPrimitive, SVMarkShape,
};
use scienceview_core::sv_scale::SVColour;

#[test]
fn the_golden_document_is_exactly_this_string() {
    let mut document = SVSvgDocument::new(SVViewport::new(20.0, 10.0))
        .with_title("Golden")
        .with_background(SVColour::new(255, 255, 255, 255));
    document.push_decoration_primitive(&SVDecorationPrimitive::line(
        SVPoint::new(0.0, 0.0),
        SVPoint::new(20.0, 0.0),
        SVStroke::new(SVColour::new(0, 0, 0, 255), 1.0),
    ));
    document.push_mark_primitive(&SVMarkPrimitive::new(
        SVMarkShape::Circle(SVGeometryCircle::new(SVMarkPoint::new(10.0, 5.0), 2.0)),
        SVMarkPaint::filled(SVColour::new(9, 105, 218, 255)),
    ));

    let expected = "\
<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"20\" height=\"10\" viewBox=\"0 0 20 10\" role=\"img\" aria-label=\"Golden\">
  <title>Golden</title>
  <desc>Figure generated by scienceview</desc>
  <rect x=\"0\" y=\"0\" width=\"20\" height=\"10\" fill=\"#ffffff\"/>
  <line x1=\"0\" y1=\"0\" x2=\"20\" y2=\"0\" stroke=\"#000000\" stroke-width=\"1\"/>
  <circle cx=\"10\" cy=\"5\" r=\"2\" fill=\"#0969da\"/>
</svg>
";

    assert_eq!(document.to_svg(), expected);
}
