//! The default figure: background, title, axes, grid and the data as a line.
//!
//! A bare `SVFigure` carries values, not a composed recipe. Until a recipe
//! adds marks and decorations, the backend still renders a legible figure: the
//! values through a vertical scale, the index through a horizontal scale, two
//! axes that share those scales and a title that names the whole thing.

use crate::document::SVSvgDocument;
use crate::figure::default_series::{SVSeries, sv_collect_series};
use scienceview_core::sv_backend::SVRenderRequest;
use scienceview_core::sv_decoration::{
    SVAxis, SVAxisSide, SVAxisSpace, SVDecorationPrimitive, SVDecorationStyle, SVGrid, SVTitle,
    SVTitleRole,
};
use scienceview_core::sv_error::SVError;
use scienceview_core::sv_layout::{SVLength, SVResolvedRectangle, SVViewport};
use scienceview_core::sv_mark::{SVMark, SVMarkRequest, SVMarkTheme};
use scienceview_core::sv_scale::{SVScale, SVScaleBuilder, SVScaleKind};

/// The viewport of every figure the documentation generates.
pub(crate) const DEFAULT_VIEWPORT_WIDTH: f64 = 640.0;
/// The height of every figure the documentation generates.
pub(crate) const DEFAULT_VIEWPORT_HEIGHT: f64 = 400.0;

const PLOT_LEFT: f64 = 64.0;
const PLOT_TOP: f64 = 56.0;
const PLOT_WIDTH: f64 = 528.0;
const PLOT_HEIGHT: f64 = 272.0;

/// Renders a bare figure request into a document string.
pub(crate) fn sv_render_default_figure(request: &SVRenderRequest<'_>) -> Result<String, SVError> {
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(DEFAULT_VIEWPORT_WIDTH, DEFAULT_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(PLOT_LEFT, PLOT_TOP, PLOT_WIDTH, PLOT_HEIGHT);
    let series = sv_collect_series(&request.view);

    let mut document = SVSvgDocument::new(viewport)
        .with_title(request.title.unwrap_or("scienceview figure"))
        .with_description("Figure generated by scienceview")
        .with_background(style.background());

    if series.points.is_empty() {
        document.push_decoration_primitive(&SVDecorationPrimitive::rectangle(
            scienceview_core::sv_decoration::SVRectanglePrimitive::outlined(
                plot,
                scienceview_core::sv_decoration::SVStroke::new(style.axis(), 1.0),
            ),
        ));
        return Ok(document.to_svg());
    }

    let horizontal_values: Vec<f64> = series.points.iter().map(|(x, _)| *x).collect();
    let vertical_values: Vec<f64> = series.points.iter().map(|(_, y)| *y).collect();
    let horizontal = sv_horizontal_scale(&series, plot)?;
    let vertical = sv_vertical_scale(&vertical_values, plot)?;

    let bottom = SVAxis::builder(SVAxisSide::Bottom).build();
    let left = SVAxis::builder(SVAxisSide::Left).build();
    let bottom_placement = bottom.place(
        &bottom.measure(&horizontal, SVAxisSpace::new(plot.width)?, &style)?,
        plot,
        &style,
    );
    let left_placement = left.place(
        &left.measure(&vertical, SVAxisSpace::new(plot.height)?, &style)?,
        plot,
        &style,
    );

    let grid = SVGrid::new().place(Some(&bottom_placement), Some(&left_placement), plot, &style);
    document.push_decoration_primitives(grid.primitives());
    document.push_decoration_primitive(&SVDecorationPrimitive::rectangle(
        scienceview_core::sv_decoration::SVRectanglePrimitive::outlined(
            plot,
            scienceview_core::sv_decoration::SVStroke::new(style.axis(), 1.0),
        ),
    ));

    let theme = SVMarkTheme::default();
    let mark: SVMark = SVMark::line()
        .width(SVLength::absolute(2.0))
        .colour(theme.mark_colour())
        .into();
    let mark_request = SVMarkRequest::new(
        scienceview_core::sv_data::SVColumnView::Dense(&horizontal_values),
        scienceview_core::sv_data::SVColumnView::Dense(&vertical_values),
        &horizontal,
        &vertical,
        plot,
    );
    document.push_mark_geometry(&mark.geometry(&mark_request)?);

    document.push_decoration_primitives(bottom_placement.primitives());
    document.push_decoration_primitives(left_placement.primitives());

    if let Some(title) = request.title {
        let title = SVTitle::new(SVTitleRole::Title, title);
        let measurement = title.measure(&style);
        let rectangle =
            SVResolvedRectangle::new(0.0, 8.0, DEFAULT_VIEWPORT_WIDTH, measurement.height());
        document
            .push_decoration_primitives(title.place(&measurement, rectangle, &style).primitives());
    }

    Ok(document.to_svg())
}

fn sv_horizontal_scale(
    series: &SVSeries,
    plot: SVResolvedRectangle,
) -> Result<SVScale<'static>, SVError> {
    let maximum = (series.logical_length.saturating_sub(1)).max(1) as f64;
    SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(0.0, maximum)
        .range(plot.x, plot.right())
        .build()
}

fn sv_vertical_scale(
    values: &[f64],
    plot: SVResolvedRectangle,
) -> Result<SVScale<'static>, SVError> {
    let (mut minimum, mut maximum) = values
        .iter()
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(low, high), value| {
            (low.min(*value), high.max(*value))
        });
    if (maximum - minimum).abs() <= f64::EPSILON {
        let padding = if minimum.abs() <= f64::EPSILON {
            1.0
        } else {
            minimum.abs() * 0.1
        };
        minimum -= padding;
        maximum += padding;
    }

    SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(minimum, maximum)
        .range(plot.bottom(), plot.y)
        .build()
}
