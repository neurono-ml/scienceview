//! The default figure: background, title and (for now) nothing else.

use crate::document::SVSvgDocument;
use scienceview_core::sv_backend::SVRenderRequest;
use scienceview_core::sv_decoration::SVDecorationStyle;
use scienceview_core::sv_error::SVError;
use scienceview_core::sv_layout::SVViewport;

/// The viewport of every figure the documentation generates.
pub(crate) const DEFAULT_VIEWPORT_WIDTH: f64 = 640.0;
/// The height of every figure the documentation generates.
pub(crate) const DEFAULT_VIEWPORT_HEIGHT: f64 = 400.0;

/// Renders a bare figure request into a document string.
pub(crate) fn sv_render_default_figure(request: &SVRenderRequest<'_>) -> Result<String, SVError> {
    let style = SVDecorationStyle::built_in();
    let title = request.title.unwrap_or("scienceview figure");

    let document = SVSvgDocument::new(SVViewport::new(
        DEFAULT_VIEWPORT_WIDTH,
        DEFAULT_VIEWPORT_HEIGHT,
    ))
    .with_title(title)
    .with_description("Figure generated by scienceview")
    .with_background(style.background());

    Ok(document.to_svg())
}
