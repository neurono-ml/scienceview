//! The React source template.
//!
//! The template is plain text with `__PLACEHOLDER__` markers; the emitter fills
//! the markers in a fixed order, so the same figure always produces the same
//! bytes. Keeping the template apart from the emitter makes the generated
//! component easy to review next to the framework it targets.

pub(super) const REACT_TEMPLATE: &str = r#"// Generated by scienceview. Regenerate from the figure instead of editing this file.
import React, { useRef } from "react";

const svFigureMarkup = __MARKUP_LITERAL__;
const svFigureData = __DATA_JSON__;
const svFigureTitle = __TITLE_LITERAL__;
const svFigureTheme = __THEME_JSON__;
const svFigureActionEventName = "scienceview-action";
const svFigureAppendedPoints = __APPENDED_POINTS__;

export default function ScienceViewFigure({
  data = svFigureData,
  markup = svFigureMarkup,
  theme = svFigureTheme,
  title = svFigureTitle,
}) {
  const host = useRef(null);
  const emitAction = (action) => {
    const node = host.current;
    if (node && typeof node.dispatchEvent === "function") {
      node.dispatchEvent(
        new CustomEvent(svFigureActionEventName, { detail: action, bubbles: true }),
      );
    }
  };
  return (
    <div
      ref={host}
      className="scienceview-figure"
      data-scienceview-backend="react"
      data-scienceview-title={title}
      data-scienceview-points={data.logicalLength}
      data-scienceview-representation={data.representation}
      data-scienceview-appended-points={svFigureAppendedPoints}
      style={theme}
      onClick={(event) =>
        emitAction({ type: "select", x: event.nativeEvent.offsetX, y: event.nativeEvent.offsetY })
      }
      onWheel={(event) => emitAction({ type: "zoom", delta: event.deltaY })}
    >
      <div dangerouslySetInnerHTML={{ __html: markup }} />
    </div>
  );
}
"#;
