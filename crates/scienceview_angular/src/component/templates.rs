//! The Angular source template.
//!
//! The template is plain text with `__PLACEHOLDER__` markers; the emitter fills
//! the markers in a fixed order, so the same figure always produces the same
//! bytes. Keeping the template apart from the emitter makes the generated
//! component easy to review next to the framework it targets.

pub(super) const ANGULAR_TEMPLATE: &str = r#"// Generated by scienceview. Regenerate from the figure instead of editing this file.
import { CommonModule } from "@angular/common";
import { Component, EventEmitter, Input, Output } from "@angular/core";

const svFigureMarkup = __MARKUP_LITERAL__;
const svFigureData = __DATA_JSON__;
const svFigureTitle = __TITLE_LITERAL__;
const svFigureTheme = __THEME_JSON__;
const svFigureActionEventName = "scienceview-action";
const svFigureAppendedPointCount = __APPENDED_POINTS__;

@Component({
  selector: "scienceview-figure",
  standalone: true,
  imports: [CommonModule],
  template: `
    <div
      class="scienceview-figure"
      data-scienceview-backend="angular"
      [attr.data-scienceview-title]="title"
      [attr.data-scienceview-points]="data.logicalLength"
      [attr.data-scienceview-representation]="data.representation"
      [attr.data-scienceview-appended-points]="appendedPoints"
      [ngStyle]="theme"
      (click)="emitAction({ type: 'select', x: $event.offsetX, y: $event.offsetY })"
      (wheel)="emitAction({ type: 'zoom', delta: $event.deltaY })"
    >
      <div [innerHTML]="markup"></div>
    </div>
  `,
})
export class ScienceViewFigureComponent {
  @Input() data: { logicalLength: number; representation: string; points: number[][] } = svFigureData;
  @Input() markup: string = svFigureMarkup;
  @Input() theme: Record<string, string> = svFigureTheme;
  @Input() title: string = svFigureTitle;
  @Output() action = new EventEmitter<{ type: string; x?: number; y?: number; delta?: number }>();

  readonly actionEventName = svFigureActionEventName;
  readonly appendedPoints = svFigureAppendedPointCount;

  emitAction(action: { type: string; x?: number; y?: number; delta?: number }): void {
    this.action.emit(action);
  }
}
"#;
