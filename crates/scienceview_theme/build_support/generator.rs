fn sv_emit_shadow(token_name: &str, value: &str) -> Result<String, String> {
    let parts: Vec<&str> = value.split_whitespace().collect();
    if parts.len() != 4 {
        return Err(format!(
            "token `{token_name}`: expected `offset_x offset_y blur_radius colour`, found `{value}`"
        ));
    }
    let offset_x = sv_emit_f64(sv_parse_number(token_name, parts[0])?);
    let offset_y = sv_emit_f64(sv_parse_number(token_name, parts[1])?);
    let blur_radius = sv_emit_f64(sv_parse_number(token_name, parts[2])?);
    let colour = sv_emit_colour(token_name, parts[3])?;
    Ok(format!(
        "crate::tokens::SVShadow::new({offset_x}, {offset_y}, {blur_radius}, {colour})"
    ))
}

fn sv_generate_motion_tokens(source: &SVThemeSource) -> Result<String, String> {
    let fast = sv_emit_f64(sv_parse_number(
        "motion.duration.fast",
        sv_value(source, "motion.duration.fast"),
    )?);
    let normal = sv_emit_f64(sv_parse_number(
        "motion.duration.normal",
        sv_value(source, "motion.duration.normal"),
    )?);
    let slow = sv_emit_f64(sv_parse_number(
        "motion.duration.slow",
        sv_value(source, "motion.duration.slow"),
    )?);
    let standard = sv_emit_easing(
        "motion.easing.standard",
        sv_value(source, "motion.easing.standard"),
    )?;
    let emphasized = sv_emit_easing(
        "motion.easing.emphasized",
        sv_value(source, "motion.easing.emphasized"),
    )?;
    let decelerate = sv_emit_easing(
        "motion.easing.decelerate",
        sv_value(source, "motion.easing.decelerate"),
    )?;
    let reduced = sv_parse_boolean("motion.reduced", sv_value(source, "motion.reduced"))?;
    Ok(format!(
        "            motion: crate::tokens::SVMotionTokens {{\n                durations: crate::tokens::SVMotionDurations {{ fast_milliseconds: {fast}, normal_milliseconds: {normal}, slow_milliseconds: {slow} }},\n                easings: crate::tokens::SVMotionEasings {{ standard: {standard}, emphasized: {emphasized}, decelerate: {decelerate} }},\n                reduced_motion: {reduced},\n            }},\n"
    ))
}

fn sv_parse_boolean(token_name: &str, value: &str) -> Result<bool, String> {
    match value {
        "true" => Ok(true),
        "false" => Ok(false),
        _ => Err(format!(
            "token `{token_name}`: expected `true` or `false`, found `{value}`"
        )),
    }
}

fn sv_emit_easing(token_name: &str, value: &str) -> Result<String, String> {
    let keyword = match value {
        "linear" => Some("Linear"),
        "ease" => Some("Ease"),
        "ease-in" => Some("EaseIn"),
        "ease-out" => Some("EaseOut"),
        "ease-in-out" => Some("EaseInOut"),
        _ => None,
    };
    if let Some(keyword) = keyword {
        return Ok(format!("crate::tokens::SVTimingFunction::{keyword}"));
    }
    let Some(arguments) = value
        .strip_prefix("cubic-bezier(")
        .and_then(|rest| rest.strip_suffix(')'))
    else {
        return Err(format!(
            "token `{token_name}`: expected a timing keyword or `cubic-bezier(x1, y1, x2, y2)`, found `{value}`"
        ));
    };
    let components: Vec<f64> = arguments
        .split(',')
        .map(|component| {
            component
                .trim()
                .parse::<f64>()
                .map_err(|_| format!("token `{token_name}`: `{component}` is not a number"))
        })
        .collect::<Result<_, _>>()?;
    if components.len() != 4 {
        return Err(format!(
            "token `{token_name}`: `cubic-bezier` needs four components, found {}",
            components.len()
        ));
    }
    if !(0.0..=1.0).contains(&components[0]) || !(0.0..=1.0).contains(&components[2]) {
        return Err(format!(
            "token `{token_name}`: the first and third `cubic-bezier` components must be within 0..=1"
        ));
    }
    Ok(format!(
        "crate::tokens::SVTimingFunction::CubicBezier {{ x1: {}, y1: {}, x2: {}, y2: {} }}",
        sv_emit_f64(components[0]),
        sv_emit_f64(components[1]),
        sv_emit_f64(components[2]),
        sv_emit_f64(components[3])
    ))
}

fn sv_generate_palettes(source: &SVThemeSource) -> Result<String, String> {
    let mut categorical = String::new();
    let mut continuous = String::new();
    for declaration in &source.declarations {
        let token_name = declaration.token_name.as_str();
        if let Some(palette_name) = token_name.strip_prefix(schema::SV_PALETTE_CATEGORICAL_PREFIX) {
            let colours = sv_emit_colour_list(token_name, &declaration.token_value)?;
            categorical.push_str(&format!(
                "                crate::palettes::SVDiscretePalette::from_validated_entries({palette_name:?}, vec![{colours}]),\n"
            ));
            continue;
        }
        let kind = [
            (schema::SV_PALETTE_SEQUENTIAL_PREFIX, "Sequential"),
            (schema::SV_PALETTE_DIVERGING_PREFIX, "Diverging"),
            (schema::SV_PALETTE_CYCLICAL_PREFIX, "Cyclical"),
        ]
        .into_iter()
        .find_map(|(prefix, kind)| token_name.strip_prefix(prefix).map(|name| (kind, name)));
        if let Some((kind, palette_name)) = kind {
            let colours = sv_emit_colour_list(token_name, &declaration.token_value)?;
            if colours.split(',').count() < 2 {
                return Err(format!(
                    "token `{token_name}`: a colour map needs at least two stops"
                ));
            }
            continuous.push_str(&format!(
                "                crate::palettes::SVContinuousPalette::from_validated_stops({palette_name:?}, crate::palettes::SVColourMapKind::{kind}, vec![{colours}]),\n"
            ));
        }
    }
    if categorical.is_empty() {
        return Err("the theme defines no categorical palette".to_string());
    }
    if continuous.is_empty() {
        return Err("the theme defines no continuous colour map".to_string());
    }
    Ok(format!(
        "        palettes: crate::palettes::SVColourPalettes {{\n            categorical: vec![\n{categorical}            ],\n            continuous: vec![\n{continuous}            ],\n        }},\n"
    ))
}

fn sv_emit_colour_list(token_name: &str, value: &str) -> Result<String, String> {
    let mut emitted = Vec::new();
    for component in value.split_whitespace() {
        emitted.push(sv_emit_colour(token_name, component)?);
    }
    if emitted.is_empty() {
        return Err(format!("token `{token_name}`: the palette is empty"));
    }
    Ok(emitted.join(", "))
}

fn sv_parse_hex_colour(value: &str) -> Result<(u8, u8, u8, u8), String> {
    let Some(hex) = value.strip_prefix('#') else {
        return Err(format!("`{value}` is not a `#rrggbb` colour"));
    };
    let digits: Vec<u8> = hex
        .chars()
        .map(|character| {
            character
                .to_digit(16)
                .map(|digit| digit as u8)
                .ok_or_else(|| format!("`{value}` contains a non-hexadecimal digit"))
        })
        .collect::<Result<_, _>>()?;
    match digits.len() {
        3 => Ok((digits[0] * 17, digits[1] * 17, digits[2] * 17, 255)),
        6 => Ok((
            digits[0] * 16 + digits[1],
            digits[2] * 16 + digits[3],
            digits[4] * 16 + digits[5],
            255,
        )),
        8 => Ok((
            digits[0] * 16 + digits[1],
            digits[2] * 16 + digits[3],
            digits[4] * 16 + digits[5],
            digits[6] * 16 + digits[7],
        )),
        _ => Err(format!("`{value}` must have 3, 6 or 8 hexadecimal digits")),
    }
}
