//! The build-time compiler: turns the parsed stylesheet into typed Rust code.
//!
//! Every value is parsed and validated here, so an invalid or missing token
//! fails the build with the offending line instead of failing a render at
//! runtime. The emitted function has the same shape the runtime compiler
//! produces, which is what makes the two paths verifiable against each other.

use super::ast::SVThemeSource;
use super::schema;

/// Compiles a parsed stylesheet into the body of `sv_generated_theme_data`.
pub fn sv_generate_theme_source(source: &SVThemeSource) -> Result<String, String> {
    let mut output = String::new();
    output.push_str("// @generated by crates/scienceview_theme/build.rs — do not edit.\n");
    output.push_str(
        "pub(crate) fn sv_generated_theme_data() -> crate::theme::SVThemeData {\n    crate::theme::SVThemeData {\n",
    );

    for token_name in schema::sv_required_token_names() {
        if source.declaration(token_name).is_none() {
            return Err(format!(
                "the required token `{token_name}` is missing from the theme stylesheet"
            ));
        }
    }

    output.push_str("        tokens: crate::tokens::SVThemeTokens {\n");
    output.push_str(&sv_generate_colour_tokens(source)?);
    output.push_str(&sv_generate_typography_tokens(source)?);
    output.push_str(&sv_generate_spacing_tokens(source)?);
    output.push_str(&sv_generate_radius_tokens(source)?);
    output.push_str(&sv_generate_shadow_tokens(source)?);
    output.push_str(&sv_generate_motion_tokens(source)?);
    output.push_str("        },\n");
    output.push_str(&sv_generate_palettes(source)?);
    output.push_str("    }\n}\n");
    Ok(output)
}

fn sv_value<'a>(source: &'a SVThemeSource, token_name: &str) -> &'a str {
    // Presence is checked before generation starts.
    &source
        .declaration(token_name)
        .expect("required token presence is validated before generation")
        .token_value
}

fn sv_emit_colour(token_name: &str, value: &str) -> Result<String, String> {
    let (red, green, blue, alpha) =
        sv_parse_hex_colour(value).map_err(|message| format!("token `{token_name}`: {message}"))?;
    Ok(format!(
        "crate::tokens::SVColour::new({red}, {green}, {blue}, {alpha})"
    ))
}

fn sv_parse_number(token_name: &str, value: &str) -> Result<f64, String> {
    value
        .parse::<f64>()
        .map_err(|_| format!("token `{token_name}`: `{value}` is not a number"))
}

fn sv_emit_f64(value: f64) -> String {
    format!("{value:?}")
}

fn sv_generate_colour_tokens(source: &SVThemeSource) -> Result<String, String> {
    let mut output = String::from("            colour: crate::tokens::SVColourTokens {\n");
    for token_name in schema::SV_COLOUR_TOKEN_NAMES {
        let field_name = token_name.trim_start_matches("colour.");
        let emitted = sv_emit_colour(token_name, sv_value(source, token_name))?;
        output.push_str(&format!("                {field_name}: {emitted},\n"));
    }
    output.push_str("            },\n");
    Ok(output)
}

fn sv_generate_typography_tokens(source: &SVThemeSource) -> Result<String, String> {
    let family = sv_value(source, "typography.family");
    let body = sv_emit_f64(sv_parse_number(
        "typography.size.body",
        sv_value(source, "typography.size.body"),
    )?);
    let title = sv_emit_f64(sv_parse_number(
        "typography.size.title",
        sv_value(source, "typography.size.title"),
    )?);
    let label = sv_emit_f64(sv_parse_number(
        "typography.size.label",
        sv_value(source, "typography.size.label"),
    )?);
    let regular = sv_parse_weight(
        "typography.weight.regular",
        sv_value(source, "typography.weight.regular"),
    )?;
    let bold = sv_parse_weight(
        "typography.weight.bold",
        sv_value(source, "typography.weight.bold"),
    )?;
    let line_height = sv_emit_f64(sv_parse_number(
        "typography.line_height",
        sv_value(source, "typography.line_height"),
    )?);
    Ok(format!(
        "            typography: crate::tokens::SVTypographyTokens {{\n                family: String::from({family:?}),\n                size: crate::tokens::SVFontSizes {{ body: {body}, title: {title}, label: {label} }},\n                weight: crate::tokens::SVFontWeights {{ regular: {regular}, bold: {bold} }},\n                line_height: {line_height},\n            }},\n"
    ))
}

fn sv_parse_weight(token_name: &str, value: &str) -> Result<u16, String> {
    value
        .parse::<u16>()
        .map_err(|_| format!("token `{token_name}`: `{value}` is not a font weight"))
}

