//! Line-plot example: renders a sine wave to `docs/figures/line_plot.svg`.
//!
//! Run with `cargo run --example line_plot_svg` from the repository root.
//! The SVG file is checked in and embedded in `README.md` and the mdBook,
//! so every figure shown in the documentation is produced by the tool itself.

use std::error::Error;
use std::fs;
use std::path::PathBuf;

const IMAGE_WIDTH: f64 = 640.0;
const IMAGE_HEIGHT: f64 = 400.0;
const PLOT_LEFT: f64 = 64.0;
const PLOT_TOP: f64 = 48.0;
const PLOT_WIDTH: f64 = 528.0;
const PLOT_HEIGHT: f64 = 280.0;
const POINT_COUNT: usize = 81;

fn manifest_directory() -> Result<PathBuf, Box<dyn Error>> {
    let directory = std::env::var("CARGO_MANIFEST_DIR")?;
    Ok(PathBuf::from(directory))
}

fn sine_sample(index: usize) -> f64 {
    let fraction = index as f64 / (POINT_COUNT - 1) as f64;
    (fraction * std::f64::consts::TAU).sin()
}

fn main() -> Result<(), Box<dyn Error>> {
    let mut samples = Vec::with_capacity(POINT_COUNT);
    for index in 0..POINT_COUNT {
        samples.push(sine_sample(index));
    }

    let mut polyline_points = String::new();
    for (index, sample) in samples.iter().enumerate() {
        let fraction = index as f64 / (POINT_COUNT - 1) as f64;
        let horizontal = PLOT_LEFT + fraction * PLOT_WIDTH;
        let vertical = PLOT_TOP + PLOT_HEIGHT / 2.0 - sample * (PLOT_HEIGHT / 2.0 - 8.0);
        if index > 0 {
            polyline_points.push(' ');
        }
        polyline_points.push_str(&format!("{horizontal:.1},{vertical:.1}"));
    }

    let mut markers = String::new();
    for (index, sample) in samples.iter().enumerate().step_by(10) {
        let fraction = index as f64 / (POINT_COUNT - 1) as f64;
        let horizontal = PLOT_LEFT + fraction * PLOT_WIDTH;
        let vertical = PLOT_TOP + PLOT_HEIGHT / 2.0 - sample * (PLOT_HEIGHT / 2.0 - 8.0);
        markers.push_str(&format!(
            "<circle cx=\"{horizontal:.1}\" cy=\"{vertical:.1}\" r=\"4.5\" fill=\"#ef4766\" stroke=\"#ffffff\" stroke-width=\"1.5\"/>\n    "
        ));
    }

    let bottom = PLOT_TOP + PLOT_HEIGHT;
    let middle = PLOT_TOP + PLOT_HEIGHT / 2.0;
    let svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{IMAGE_WIDTH:.0}\" height=\"{IMAGE_HEIGHT:.0}\" viewBox=\"0 0 {IMAGE_WIDTH:.0} {IMAGE_HEIGHT:.0}\" role=\"img\" aria-label=\"Sine wave line plot generated by scienceview\">\n  \
         <rect x=\"0\" y=\"0\" width=\"{IMAGE_WIDTH:.0}\" height=\"{IMAGE_HEIGHT:.0}\" fill=\"#ffffff\"/>\n  \
         <text x=\"{:.0}\" y=\"28\" font-family=\"sans-serif\" font-size=\"20\" font-weight=\"bold\" fill=\"#1d3557\">Sine wave (scienceview SVG backend)</text>\n  \
         <line x1=\"{PLOT_LEFT:.0}\" y1=\"{middle:.0}\" x2=\"{:.0}\" y2=\"{middle:.0}\" stroke=\"#e0e0e0\" stroke-width=\"1\"/>\n  \
         <rect x=\"{PLOT_LEFT:.0}\" y=\"{PLOT_TOP:.0}\" width=\"{PLOT_WIDTH:.0}\" height=\"{PLOT_HEIGHT:.0}\" fill=\"none\" stroke=\"#1d3557\" stroke-width=\"2\"/>\n  \
         <polyline points=\"{polyline_points}\" fill=\"none\" stroke=\"#118ab2\" stroke-width=\"3\" stroke-linejoin=\"round\" stroke-linecap=\"round\"/>\n  \
         {markers}<text x=\"{PLOT_LEFT:.0}\" y=\"{:.0}\" font-family=\"sans-serif\" font-size=\"13\" fill=\"#457b9d\">0</text>\n  \
         <text x=\"{:.0}\" y=\"{:.0}\" font-family=\"sans-serif\" font-size=\"13\" fill=\"#457b9d\">2π</text>\n  \
         <text x=\"8\" y=\"{:.0}\" font-family=\"sans-serif\" font-size=\"13\" fill=\"#457b9d\">+1</text>\n  \
         <text x=\"8\" y=\"{:.0}\" font-family=\"sans-serif\" font-size=\"13\" fill=\"#457b9d\">−1</text>\n</svg>\n",
        IMAGE_WIDTH / 2.0 - 190.0,
        PLOT_LEFT + PLOT_WIDTH,
        bottom + 24.0,
        PLOT_LEFT + PLOT_WIDTH - 12.0,
        bottom - 6.0,
        PLOT_TOP + 16.0,
        bottom - 4.0,
    );

    let root = manifest_directory()?;
    let figures = root.join("docs").join("figures");
    fs::create_dir_all(&figures)?;
    let destination = figures.join("line_plot.svg");
    fs::write(&destination, svg)?;
    println!("Wrote {}", destination.display());
    Ok(())
}
