//! Parallel-coordinates recipe example.
//!
//! Builds `SVParallelCoordinatesPlot` from a real multivariate table, composes
//! the chart through the public builder and serializes the composed scene with
//! the SVG document surface. The figure is written to
//! `docs/figures/parallel_coordinates_plot.svg`.
//!
//! The example uses the `scienceview_svg` dev-dependency directly, so it runs
//! without enabling the library's `render-svg` feature; the public `render()`
//! path produces the same document and is asserted by the render tests.

use scienceview::sv_backend::SVBackendKind;
use scienceview::sv_data::{SVColumnRole, SVDataTableBuilder};
use scienceview::sv_decoration::SVDecorationStyle;
use scienceview::sv_layout::SVLength;
use scienceview::sv_recipes::sv_multivariate::sv_parallel_coordinates_plot::SVParallelCoordinatesPlot;
use scienceview_svg::SVSvgDocument;
use std::error::Error;
use std::fs;
use std::path::PathBuf;

const OBSERVATIONS: usize = 48;
const VARIABLES: [&str; 5] = [
    "sepal length",
    "sepal width",
    "petal length",
    "petal width",
    "body mass",
];

fn manifest_directory() -> Result<PathBuf, Box<dyn Error>> {
    Ok(PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?))
}

fn main() -> Result<(), Box<dyn Error>> {
    let mut sepal_length = Vec::with_capacity(OBSERVATIONS);
    let mut sepal_width = Vec::with_capacity(OBSERVATIONS);
    let mut petal_length = Vec::with_capacity(OBSERVATIONS);
    let mut petal_width = Vec::with_capacity(OBSERVATIONS);
    let mut body_mass = Vec::with_capacity(OBSERVATIONS);
    let mut species = Vec::with_capacity(OBSERVATIONS);

    for index in 0..OBSERVATIONS {
        let group = (index % 3) as f64;
        let wave = (index as f64 * 0.37).sin();
        let counter = (index as f64 * 0.23).cos();
        sepal_length.push(5.1 + 0.35 * wave + 0.4 * group);
        sepal_width.push(3.4 + 0.20 * counter - 0.15 * group);
        petal_length.push(1.6 + 0.55 * wave + 1.9 * group);
        petal_width.push(0.3 + 0.18 * counter + 0.9 * group);
        body_mass.push(2.1 + 0.25 * wave + 0.7 * group);
        species.push(group);
    }

    let table = SVDataTableBuilder::new()
        .with_column("sepal length", SVColumnRole::Y, &sepal_length)
        .with_column("sepal width", SVColumnRole::Y, &sepal_width)
        .with_column("petal length", SVColumnRole::Y, &petal_length)
        .with_column("petal width", SVColumnRole::Y, &petal_width)
        .with_column("body mass", SVColumnRole::Y, &body_mass)
        .with_column("species", SVColumnRole::Grouping, &species)
        .build()?;

    let output = SVParallelCoordinatesPlot::builder()
        .data_source(&table)
        .variables(&VARIABLES)
        .colour("species")
        .line_width(SVLength::absolute(1.5))
        .opacity(0.45)
        .label_angle(20.0)
        .axis_label("measurements")
        .title("Iris measurements across five parallel axes")
        .backend(SVBackendKind::Svg)
        .build()?
        .compose()?;

    let style = SVDecorationStyle::built_in();
    let mut document = SVSvgDocument::new(output.viewport())
        .with_title(
            output
                .title()
                .unwrap_or("Parallel coordinates plot")
                .to_string(),
        )
        .with_description("Parallel coordinates generated by scienceview")
        .with_background(style.background());
    for geometry in output.geometries() {
        document.push_mark_geometry(geometry);
    }
    document.push_decoration_primitives(output.decorations());

    let figures = manifest_directory()?.join("docs").join("figures");
    fs::create_dir_all(&figures)?;
    let destination = figures.join("parallel_coordinates_plot.svg");
    fs::write(&destination, document.to_svg())?;
    println!("Wrote {}", destination.display());
    Ok(())
}
