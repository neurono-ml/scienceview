//! Bar-chart example: renders sample values to `docs/figures/bar_chart.svg`.
//!
//! Run with `cargo run --example bar_chart_svg` from the repository root.
//! The SVG file is checked in and embedded in `README.md` and the mdBook,
//! so every figure shown in the documentation is produced by the tool itself.

use std::error::Error;
use std::fs;
use std::path::PathBuf;

const IMAGE_WIDTH: f64 = 640.0;
const IMAGE_HEIGHT: f64 = 400.0;
const PLOT_LEFT: f64 = 64.0;
const PLOT_TOP: f64 = 56.0;
const PLOT_WIDTH: f64 = 528.0;
const PLOT_HEIGHT: f64 = 272.0;

const LABELS: [&str; 5] = ["Alpha", "Beta", "Gamma", "Delta", "Epsilon"];
const VALUES: [f64; 5] = [4.0, 7.0, 3.0, 8.0, 5.0];
const COLORS: [&str; 5] = ["#118ab2", "#06d6a0", "#e9c46a", "#ef4766", "#8338ec"];
const MAXIMUM_VALUE: f64 = 8.0;

fn manifest_directory() -> Result<PathBuf, Box<dyn Error>> {
    let directory = std::env::var("CARGO_MANIFEST_DIR")?;
    Ok(PathBuf::from(directory))
}

fn main() -> Result<(), Box<dyn Error>> {
    let slot = PLOT_WIDTH / LABELS.len() as f64;
    let bar_width = slot * 0.56;
    let bottom = PLOT_TOP + PLOT_HEIGHT;

    let mut bars = String::new();
    for (index, (label, value)) in LABELS.iter().zip(VALUES.iter()).enumerate() {
        let height = value / MAXIMUM_VALUE * (PLOT_HEIGHT - 24.0);
        let left = PLOT_LEFT + slot * index as f64 + (slot - bar_width) / 2.0;
        let top = bottom - height;
        let center = left + bar_width / 2.0;
        let color = COLORS[index % COLORS.len()];
        bars.push_str(&format!(
            "<rect x=\"{left:.1}\" y=\"{top:.1}\" width=\"{bar_width:.1}\" height=\"{height:.1}\" rx=\"6\" fill=\"{color}\" stroke=\"#1d3557\" stroke-width=\"1.5\"/>\n    \
             <text x=\"{center:.1}\" y=\"{:.1}\" text-anchor=\"middle\" font-family=\"sans-serif\" font-size=\"14\" font-weight=\"bold\" fill=\"#1d3557\">{value:.0}</text>\n    \
             <text x=\"{center:.1}\" y=\"{:.1}\" text-anchor=\"middle\" font-family=\"sans-serif\" font-size=\"13\" fill=\"#457b9d\">{label}</text>\n    ",
            top - 8.0,
            bottom + 22.0,
        ));
    }

    let mut grid = String::new();
    for step in 0..=4 {
        let value = MAXIMUM_VALUE * step as f64 / 4.0;
        let vertical = bottom - value / MAXIMUM_VALUE * (PLOT_HEIGHT - 24.0);
        grid.push_str(&format!(
            "<line x1=\"{PLOT_LEFT:.0}\" y1=\"{vertical:.1}\" x2=\"{:.0}\" y2=\"{vertical:.1}\" stroke=\"#e0e0e0\" stroke-width=\"1\"/>\n    \
             <text x=\"{:.0}\" y=\"{:.1}\" text-anchor=\"end\" font-family=\"sans-serif\" font-size=\"12\" fill=\"#457b9d\">{value:.0}</text>\n    ",
            PLOT_LEFT + PLOT_WIDTH,
            PLOT_LEFT - 8.0,
            vertical + 4.0,
        ));
    }

    let svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{IMAGE_WIDTH:.0}\" height=\"{IMAGE_HEIGHT:.0}\" viewBox=\"0 0 {IMAGE_WIDTH:.0} {IMAGE_HEIGHT:.0}\" role=\"img\" aria-label=\"Bar chart generated by scienceview\">\n  \
         <rect x=\"0\" y=\"0\" width=\"{IMAGE_WIDTH:.0}\" height=\"{IMAGE_HEIGHT:.0}\" fill=\"#ffffff\"/>\n  \
         <text x=\"{:.0}\" y=\"30\" font-family=\"sans-serif\" font-size=\"20\" font-weight=\"bold\" fill=\"#1d3557\">Sample bars (scienceview SVG backend)</text>\n  \
         {grid}<rect x=\"{PLOT_LEFT:.0}\" y=\"{PLOT_TOP:.0}\" width=\"{PLOT_WIDTH:.0}\" height=\"{PLOT_HEIGHT:.0}\" fill=\"none\" stroke=\"#1d3557\" stroke-width=\"2\"/>\n  \
         {bars}</svg>\n",
        IMAGE_WIDTH / 2.0 - 200.0,
    );

    let root = manifest_directory()?;
    let figures = root.join("docs").join("figures");
    fs::create_dir_all(&figures)?;
    let destination = figures.join("bar_chart.svg");
    fs::write(&destination, svg)?;
    println!("Wrote {}", destination.display());
    Ok(())
}
