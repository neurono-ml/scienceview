//! Scatter example: composes a scatter plot from the real builders and writes
//! `docs/figures/scatter_plot.svg`.
//!
//! Run with `cargo run --example scatter_svg` from the repository root.
//! The figure is checked in and embedded in `README.md` and the mdBook, so the
//! picture shown in the documentation is produced by the tool itself:
//! data source → scales → dot marks → decorations → SVG serialization.

use scienceview_core::sv_data::SVColumnView;
use scienceview_core::sv_decoration::{
    SVAxis, SVAxisSide, SVAxisSpace, SVDecorationStyle, SVGrid, SVLegend, SVTitle, SVTitleRole,
};
use scienceview_core::sv_layout::{SVLength, SVResolvedRectangle, SVViewport};
use scienceview_core::sv_mark::{SVDotShape, SVMark, SVMarkRequest};
use scienceview_core::sv_scale::{SVColour, SVScaleBuilder, SVScaleKind};
use scienceview_svg::SVSvgDocument;
use std::error::Error;
use std::fs;
use std::path::PathBuf;

const IMAGE_WIDTH: f64 = 640.0;
const IMAGE_HEIGHT: f64 = 400.0;
const PLOT_LEFT: f64 = 72.0;
const PLOT_TOP: f64 = 56.0;
const PLOT_WIDTH: f64 = 492.0;
const PLOT_HEIGHT: f64 = 272.0;

const FIRST_SERIES_HORIZONTAL: [f64; 9] = [1.0, 1.8, 2.5, 3.2, 4.1, 5.0, 5.7, 6.4, 7.2];
const FIRST_SERIES_VERTICAL: [f64; 9] = [2.1, 2.8, 3.6, 4.2, 5.1, 5.8, 6.6, 7.1, 8.0];
const SECOND_SERIES_HORIZONTAL: [f64; 8] = [2.2, 3.0, 3.9, 4.8, 5.5, 6.3, 7.0, 8.1];
const SECOND_SERIES_VERTICAL: [f64; 8] = [1.2, 1.9, 2.4, 3.1, 3.6, 4.4, 5.0, 6.2];

const FIRST_SERIES_COLOUR: SVColour = SVColour::new(9, 105, 218, 255);
const SECOND_SERIES_COLOUR: SVColour = SVColour::new(239, 71, 102, 255);

fn manifest_directory() -> Result<PathBuf, Box<dyn Error>> {
    let directory = std::env::var("CARGO_MANIFEST_DIR")?;
    Ok(PathBuf::from(directory))
}

fn main() -> Result<(), Box<dyn Error>> {
    let style = SVDecorationStyle::built_in();
    let plot = SVResolvedRectangle::new(PLOT_LEFT, PLOT_TOP, PLOT_WIDTH, PLOT_HEIGHT);

    let horizontal = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(0.0, 9.0)
        .range(plot.x, plot.right())
        .build()?;
    let vertical = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(0.0, 9.0)
        .range(plot.bottom(), plot.y)
        .build()?;

    let bottom_axis = SVAxis::builder(SVAxisSide::Bottom)
        .title("sepal width")
        .build();
    let left_axis = SVAxis::builder(SVAxisSide::Left)
        .title("petal length")
        .build();
    let bottom = bottom_axis.place(
        &bottom_axis.measure(&horizontal, SVAxisSpace::new(plot.width)?, &style)?,
        plot,
        &style,
    );
    let left = left_axis.place(
        &left_axis.measure(&vertical, SVAxisSpace::new(plot.height)?, &style)?,
        plot,
        &style,
    );
    let grid = SVGrid::new().place(Some(&bottom), Some(&left), plot, &style);

    let mut document = SVSvgDocument::new(SVViewport::new(IMAGE_WIDTH, IMAGE_HEIGHT))
        .with_title("Sepal width against petal length")
        .with_description("Two series of a scatter plot generated by scienceview")
        .with_background(style.background());

    let title = SVTitle::new(SVTitleRole::Title, "Sepal width against petal length");
    let title_measurement = title.measure(&style);
    document.push_decoration_primitives(
        title
            .place(
                &title_measurement,
                SVResolvedRectangle::new(0.0, 8.0, IMAGE_WIDTH, title_measurement.height()),
                &style,
            )
            .primitives(),
    );

    document.push_decoration_primitives(grid.primitives());

    document.push_mark_geometry(&scatter_series(
        &FIRST_SERIES_HORIZONTAL,
        &FIRST_SERIES_VERTICAL,
        FIRST_SERIES_COLOUR,
        &horizontal,
        &vertical,
        plot,
    )?);
    document.push_mark_geometry(&scatter_series(
        &SECOND_SERIES_HORIZONTAL,
        &SECOND_SERIES_VERTICAL,
        SECOND_SERIES_COLOUR,
        &horizontal,
        &vertical,
        plot,
    )?);

    document.push_decoration_primitives(bottom.primitives());
    document.push_decoration_primitives(left.primitives());

    let mut legend = SVLegend::new();
    legend.add_series("first", "setosa", FIRST_SERIES_COLOUR);
    legend.add_series("second", "versicolor", SECOND_SERIES_COLOUR);
    let legend_measurement = legend.measure(&style);
    let legend_rectangle = SVResolvedRectangle::new(
        plot.right() + 16.0,
        plot.y,
        legend_measurement.width(),
        legend_measurement.height(),
    );
    document.push_decoration_primitives(
        legend
            .place(&legend_measurement, legend_rectangle, &style)
            .primitives(),
    );

    let root = manifest_directory()?;
    let figures = root.join("docs").join("figures");
    fs::create_dir_all(&figures)?;
    let destination = figures.join("scatter_plot.svg");
    fs::write(&destination, document.to_svg())?;
    println!("Wrote {}", destination.display());
    Ok(())
}

fn scatter_series<'scales>(
    horizontal_values: &'scales [f64],
    vertical_values: &'scales [f64],
    colour: SVColour,
    horizontal_scale: &'scales scienceview_core::sv_scale::SVScale<'scales>,
    vertical_scale: &'scales scienceview_core::sv_scale::SVScale<'scales>,
    plot: SVResolvedRectangle,
) -> Result<scienceview_core::sv_mark::SVMarkGeometry<'scales>, Box<dyn Error>> {
    let mark: SVMark = SVMark::dot()
        .shape(SVDotShape::Circle)
        .size(SVLength::absolute(8.0))
        .colour(colour)
        .into();
    let request = SVMarkRequest::new(
        SVColumnView::Dense(horizontal_values),
        SVColumnView::Dense(vertical_values),
        horizontal_scale,
        vertical_scale,
        plot,
    );

    Ok(mark.geometry(&request)?)
}
