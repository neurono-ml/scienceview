//! Density-contour recipe example.
//!
//! Draws the joint distribution of two synthetic measurements as filled
//! contours. The sample is generated deterministically from a small linear
//! congruential generator, so the checked-in figure never drifts. The example
//! composes the public builder and serializes the backend-agnostic scene with
//! the SVG document surface, exactly like the other recipe examples.

use scienceview::sv_backend::SVBackendKind;
use scienceview::sv_data::{SVColumnRole, SVDataTable};
use scienceview::sv_decoration::SVDecorationStyle;
use scienceview::sv_recipes::sv_distribution::sv_density_contour_plot::SVDensityContourPlot;
use scienceview_svg::SVSvgDocument;
use std::error::Error;
use std::fs;
use std::path::PathBuf;

const SAMPLE_COUNT: usize = 720;

fn manifest_directory() -> Result<PathBuf, Box<dyn Error>> {
    Ok(PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?))
}

/// A tiny deterministic generator; the figure must not depend on entropy.
struct SVLinearCongruential {
    state: u64,
}

impl SVLinearCongruential {
    fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    fn next_unit(&mut self) -> f64 {
        self.state = self
            .state
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        ((self.state >> 11) as f64) / ((1u64 << 53) as f64)
    }

    /// Box–Muller transforms two uniforms into one standard normal sample.
    fn next_normal(&mut self) -> f64 {
        let first = self.next_unit().max(f64::MIN_POSITIVE);
        let second = self.next_unit();
        (-2.0 * first.ln()).sqrt() * (std::f64::consts::TAU * second).cos()
    }
}

fn main() -> Result<(), Box<dyn Error>> {
    let mut generator = SVLinearCongruential::new(0x5EED_1234);
    let mut horizontal = Vec::with_capacity(SAMPLE_COUNT);
    let mut vertical = Vec::with_capacity(SAMPLE_COUNT);
    for index in 0..SAMPLE_COUNT {
        if index % 2 == 0 {
            horizontal.push(1.6 + 0.75 * generator.next_normal());
            vertical.push(2.2 + 0.9 * generator.next_normal());
        } else {
            horizontal.push(4.6 + 0.9 * generator.next_normal());
            vertical.push(5.1 + 0.7 * generator.next_normal());
        }
    }

    let table = SVDataTable::builder()
        .with_column("first measurement", SVColumnRole::X, &horizontal)
        .with_column("second measurement", SVColumnRole::Y, &vertical)
        .build()?;

    let plot = SVDensityContourPlot::builder()
        .data_source(&table)
        .x("first measurement")
        .y("second measurement")
        .grid_count(96)
        .bandwidth(0.35)
        .levels(9)
        .title("Joint distribution of two measurements")
        .x_label("first measurement")
        .y_label("second measurement")
        .backend(SVBackendKind::Svg)
        .build()?;

    let composition = plot.compose()?;
    let style = SVDecorationStyle::built_in();
    let mut document = SVSvgDocument::new(composition.viewport())
        .with_title(composition.title().unwrap_or("Density contour plot"))
        .with_description("Density contour plot generated by scienceview")
        .with_background(style.background());
    document.push_decoration_primitives(composition.decoration_primitives_before_marks());
    composition.visit_mark_geometries(|geometry| document.push_mark_geometry(geometry))?;
    document.push_decoration_primitives(composition.decoration_primitives_after_marks());

    let figures = manifest_directory()?.join("docs").join("figures");
    fs::create_dir_all(&figures)?;
    let destination = figures.join("density_contour_plot.svg");
    fs::write(&destination, document.to_svg())?;
    println!("Wrote {}", destination.display());
    Ok(())
}
