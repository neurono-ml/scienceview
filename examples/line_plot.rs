//! Line-plot recipe example.
//!
//! Builds `SVLinePlot` from a real multi-series dataset, composes the chart
//! with the recipe and serializes the result through the SVG backend's
//! document surface. The figure is written to
//! `docs/figures/line_plot_recipe.svg`; the name is distinct from the
//! `line_plot_svg` example's figure so the two never drift against each other.

use scienceview::recipes::relational::line_plot::SVLinePlotBuilder;
use scienceview_core::sv_backend::SVBackendKind;
use scienceview_core::sv_data::SVColumnView;
use scienceview_core::sv_decoration::SVDecorationStyle;
use scienceview_core::sv_layout::SVLength;
use scienceview_svg::SVSvgDocument;
use std::error::Error;
use std::fs;
use std::path::PathBuf;

const SAMPLE_COUNT: usize = 81;

fn manifest_directory() -> Result<PathBuf, Box<dyn Error>> {
    Ok(PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?))
}

fn main() -> Result<(), Box<dyn Error>> {
    let phases: Vec<f64> = (0..SAMPLE_COUNT)
        .map(|index| index as f64 / (SAMPLE_COUNT - 1) as f64 * std::f64::consts::TAU)
        .collect();
    let mut x = Vec::with_capacity(SAMPLE_COUNT * 2);
    let mut y = Vec::with_capacity(SAMPLE_COUNT * 2);
    let mut series = Vec::with_capacity(SAMPLE_COUNT * 2);
    for (index, value) in phases.iter().enumerate() {
        let damping = (-0.15 * index as f64).exp();
        x.push(*value);
        y.push(damping * value.sin());
        series.push(0.0);
        x.push(*value);
        y.push(damping * value.cos());
        series.push(1.0);
    }

    let plot = SVLinePlotBuilder::new()
        .x(SVColumnView::Dense(&x))
        .y(SVColumnView::Dense(&y))
        .series(SVColumnView::Dense(&series))
        .markers(true)
        .line_width(SVLength::absolute(2.0))
        .title("Damped oscillation by series")
        .x_axis_title("phase")
        .y_axis_title("amplitude")
        .backend(SVBackendKind::Svg)
        .build()?;

    let composition = plot.compose()?;
    let style = SVDecorationStyle::built_in();
    let mut document = SVSvgDocument::new(composition.viewport())
        .with_title(composition.title().unwrap_or("A line plot"))
        .with_description("Line plot generated by scienceview")
        .with_background(style.background());
    document.push_decoration_primitives(composition.decorations());
    composition.visit_mark_geometries(|geometry| document.push_mark_geometry(geometry))?;

    let figures = manifest_directory()?.join("docs").join("figures");
    fs::create_dir_all(&figures)?;
    let destination = figures.join("line_plot_recipe.svg");
    fs::write(&destination, document.to_svg())?;
    println!("Wrote {}", destination.display());
    Ok(())
}
