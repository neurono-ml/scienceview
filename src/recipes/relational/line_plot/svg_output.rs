//! Rendering the composed chart through the real SVG backend.

use scienceview_core::sv_decoration::SVDecorationStyle;
use scienceview_core::sv_error::SVError;
use scienceview_svg::SVSvgDocument;

use super::SVLinePlot;

pub(super) fn sv_line_plot_document(plot: &SVLinePlot<'_>) -> Result<String, SVError> {
    let composition = plot.compose()?;
    let style = SVDecorationStyle::built_in();
    let mut document = SVSvgDocument::new(composition.viewport())
        .with_title(composition.title().unwrap_or("scienceview line plot"))
        .with_description("Line plot generated by scienceview")
        .with_background(style.background());

    document.push_decoration_primitives(composition.decorations());
    composition.visit_mark_geometries(|geometry| document.push_mark_geometry(geometry))?;

    Ok(document.to_svg())
}
