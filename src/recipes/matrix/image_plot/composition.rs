//! One render: map the raster, derive the extent and compose the scene.

use super::SVImageSource;
use super::configuration::{
    SV_IMAGE_PLOT_HEIGHT, SV_IMAGE_PLOT_LEFT, SV_IMAGE_PLOT_TOP, SV_IMAGE_PLOT_WIDTH,
    SV_IMAGE_VIEWPORT_HEIGHT, SV_IMAGE_VIEWPORT_WIDTH, SVImageConfiguration, sv_resolved_extent,
};
use super::decorations::sv_image_decorations;
use super::rasterise::{sv_image_rectangle, sv_map_colour, sv_map_intensity};
use super::scene::SVImageScene;
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};
use crate::sv_scale::SVContinuousColourScale;

pub(super) fn sv_compose_scene(
    configuration: &SVImageConfiguration<'_>,
) -> Result<SVImageScene, SVError> {
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(SV_IMAGE_VIEWPORT_WIDTH, SV_IMAGE_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_IMAGE_PLOT_LEFT,
        SV_IMAGE_PLOT_TOP,
        SV_IMAGE_PLOT_WIDTH,
        SV_IMAGE_PLOT_HEIGHT,
    );
    let dimensions = configuration.source.dimensions();
    let image_rectangle = sv_image_rectangle(configuration, plot)?;
    let extent = sv_resolved_extent(configuration);

    let (raster, colour_scale): (Vec<u8>, Option<SVContinuousColourScale>) =
        match &configuration.source {
            SVImageSource::Intensity { column, .. } => {
                let mut snapshot = configuration.data_source.column(column)?;
                let mapping = sv_map_intensity(&mut snapshot, configuration)?;
                (mapping.pixels, Some(mapping.colour_scale))
            }
            SVImageSource::Colour { pixels, .. } => (
                sv_map_colour(pixels, dimensions, configuration.origin),
                None,
            ),
        };

    let (before_marks, after_marks) =
        sv_image_decorations(configuration, plot, viewport, colour_scale.as_ref());

    Ok(SVImageScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        image_rectangle,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some("Image plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        decoration_primitives_after_marks: after_marks,
        raster,
        dimensions,
        interpolation: configuration.interpolation,
        opacity: configuration.opacity,
        extent,
    })
}
