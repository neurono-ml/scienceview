//! One render: prepare the matrix, derive the colour scale and compose the scene.

mod grid;
mod painting;

use self::grid::SVHeatmapGrid;
use self::painting::{sv_cell_paint, sv_colour_scale};

use super::SVMissingValue;
use super::configuration::{
    SV_HEATMAP_PLOT_HEIGHT, SV_HEATMAP_PLOT_LEFT, SV_HEATMAP_PLOT_TOP,
    SV_HEATMAP_PLOT_WIDTH_WITH_BAR, SV_HEATMAP_PLOT_WIDTH_WITHOUT_BAR, SV_HEATMAP_VIEWPORT_HEIGHT,
    SV_HEATMAP_VIEWPORT_WIDTH, SVHeatmapConfiguration,
};
use super::decorations::{sv_cell_annotation, sv_colour_bar_primitives, sv_heatmap_decorations};
use super::preparation::sv_prepare;
use super::scene::{SVHeatmapCell, SVHeatmapScene};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};
use crate::sv_mark::{SVGeometryRectangle, SVMarkGeometry, SVMarkPrimitive, SVMarkShape};

pub(super) fn sv_compose_scene(
    configuration: &SVHeatmapConfiguration<'_>,
) -> Result<SVHeatmapScene, SVError> {
    let prepared = sv_prepare(configuration)?;
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(SV_HEATMAP_VIEWPORT_WIDTH, SV_HEATMAP_VIEWPORT_HEIGHT);
    let plot_width = if configuration.colour_bar {
        SV_HEATMAP_PLOT_WIDTH_WITH_BAR
    } else {
        SV_HEATMAP_PLOT_WIDTH_WITHOUT_BAR
    };
    let plot = SVResolvedRectangle::new(
        SV_HEATMAP_PLOT_LEFT,
        SV_HEATMAP_PLOT_TOP,
        plot_width,
        SV_HEATMAP_PLOT_HEIGHT,
    );
    let colour_scale = sv_colour_scale(configuration, &prepared)?;
    let grid = SVHeatmapGrid::new(
        plot,
        configuration.orientation,
        prepared.row_labels.len(),
        prepared.column_labels.len(),
        configuration.square,
    );

    let mut primitives = Vec::new();
    let mut cells = Vec::new();
    let mut annotations = Vec::new();
    for prepared_cell in &prepared.cells {
        let rectangle = grid.rectangle(prepared_cell.row, prepared_cell.column);
        let finite = prepared_cell.value.is_finite();
        let colour = if finite {
            Some(colour_scale.colour(prepared_cell.value)?)
        } else {
            None
        };
        let paint = sv_cell_paint(configuration, finite, colour, &style);
        let Some(paint) = paint else {
            continue;
        };
        primitives.push(SVMarkPrimitive::new(
            SVMarkShape::Rectangle(SVGeometryRectangle::new(rectangle, 0.0)),
            paint,
        ));
        let rendered_colour = if finite {
            colour
        } else if configuration.missing == SVMissingValue::Neutral {
            Some(style.surface())
        } else {
            None
        };
        cells.push(SVHeatmapCell::new(
            prepared_cell.row,
            prepared_cell.column,
            finite.then_some(prepared_cell.value),
            rendered_colour,
        ));
        if finite {
            if let Some(annotation) = sv_cell_annotation(
                prepared_cell.value,
                colour,
                rectangle,
                configuration,
                &style,
            ) {
                annotations.push(annotation);
            }
        }
    }

    let (before_marks, mut after_marks) = sv_heatmap_decorations(
        configuration,
        &prepared.row_labels,
        &prepared.column_labels,
        plot,
        viewport,
        &style,
    )?;
    after_marks.extend(annotations);
    after_marks.extend(sv_colour_bar_primitives(
        configuration.colour_bar,
        &colour_scale,
        plot,
        &style,
    )?);

    let number_of_marks = cells.len();
    Ok(SVHeatmapScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some("Heatmap generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries: vec![SVMarkGeometry::new(primitives)],
        decoration_primitives_after_marks: after_marks,
        row_labels: prepared.row_labels,
        column_labels: prepared.column_labels,
        cells,
        colour_scale,
        number_of_marks,
    })
}
