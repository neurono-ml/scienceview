pub(super) fn sv_compose_scene(
    configuration: &SVClusteredHeatmapConfiguration<'_>,
) -> Result<SVClusteredHeatmapScene, SVError> {
    let prepared = sv_prepare(configuration)?;
    sv_validate_supplied_clustering(configuration, &prepared)?;
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(SV_CLUSTERED_VIEWPORT_WIDTH, SV_CLUSTERED_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_CLUSTERED_PLOT_LEFT,
        SV_CLUSTERED_PLOT_TOP,
        SV_CLUSTERED_PLOT_WIDTH,
        SV_CLUSTERED_PLOT_HEIGHT,
    );
    let colour_scale = sv_colour_scale(configuration, &prepared)?;
    let grid = SVClusteredHeatmapGrid::new(
        plot,
        prepared.number_of_rows(),
        prepared.number_of_columns(),
    );

    let row_slot = sv_slot_of_each_original(configuration.row_order);
    let column_slot = sv_slot_of_each_original(configuration.column_order);
    let row_labels = sv_reordered_labels(&prepared.row_labels, configuration.row_order);
    let column_labels = sv_reordered_labels(&prepared.column_labels, configuration.column_order);

    let mut primitives = Vec::new();
    let mut cells = Vec::new();
    for prepared_cell in &prepared.cells {
        let slot_row = row_slot[prepared_cell.row];
        let slot_column = column_slot[prepared_cell.column];
        let rectangle = grid.rectangle(slot_row, slot_column);
        let finite = prepared_cell.value.is_finite();
        let colour = if finite {
            Some(colour_scale.colour(prepared_cell.value)?)
        } else {
            None
        };
        let Some(paint) = sv_cell_paint(configuration, finite, colour, &style) else {
            continue;
        };
        primitives.push(SVMarkPrimitive::new(
            SVMarkShape::Rectangle(SVGeometryRectangle::new(rectangle, 0.0)),
            paint,
        ));
        let rendered_colour = if finite {
            colour
        } else if configuration.missing == SVMissingValue::Neutral {
            Some(style.surface())
        } else {
            None
        };
        cells.push(SVClusteredHeatmapCell::new(
            slot_row,
            slot_column,
            prepared_cell.row,
            prepared_cell.column,
            finite.then_some(prepared_cell.value),
            rendered_colour,
        ));
    }

    let mut mark_geometries = vec![SVMarkGeometry::new(primitives)];
    let row_dendrogram = sv_build_dendrogram(
        configuration,
        SVClusterAxis::Row,
        &row_labels,
        plot,
        &style,
        &mut mark_geometries,
    );
    let column_dendrogram = sv_build_dendrogram(
        configuration,
        SVClusterAxis::Column,
        &column_labels,
        plot,
        &style,
        &mut mark_geometries,
    );

    let (before_marks, mut after_marks) = sv_heatmap_decorations(
        configuration,
        &row_labels,
        &column_labels,
        plot,
        viewport,
        &style,
    )?;
    after_marks.extend(sv_colour_bar_primitives(
        configuration.colour_bar,
        &colour_scale,
        plot,
        &style,
    )?);

    let number_of_marks = cells.len();
    Ok(SVClusteredHeatmapScene {
        backend_kind: configuration.backend_kind,
        viewport,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some(
            "Clustered heatmap generated by scienceview from a supplied clustering".to_string(),
        ),
        decoration_primitives_before_marks: before_marks,
        mark_geometries,
        decoration_primitives_after_marks: after_marks,
        row_labels,
        column_labels,
        cells,
        colour_scale,
        row_dendrogram,
        column_dendrogram,
        number_of_marks,
    })
}

fn sv_slot_of_each_original(order: &[usize]) -> Vec<usize> {
    let mut slot = vec![0_usize; order.len()];
    for (position, original) in order.iter().copied().enumerate() {
        if let Some(entry) = slot.get_mut(original) {
            *entry = position;
        }
    }
    slot
}

fn sv_reordered_labels(labels: &[String], order: &[usize]) -> Vec<String> {
    order
        .iter()
        .filter_map(|original| labels.get(*original).cloned())
        .collect()
}

fn sv_build_dendrogram(
    configuration: &SVClusteredHeatmapConfiguration<'_>,
    axis: SVClusterAxis,
    labels: &[String],
    plot: SVResolvedRectangle,
    style: &SVDecorationStyle,
    geometries: &mut Vec<SVMarkGeometry<'static>>,
) -> Option<SVDendrogram> {
    if !configuration.dendrogram {
        return None;
    }
    let tree = match axis {
        SVClusterAxis::Row => configuration.row_tree?,
        SVClusterAxis::Column => configuration.column_tree?,
    };
    let order = match axis {
        SVClusterAxis::Row => configuration.row_order,
        SVClusterAxis::Column => configuration.column_order,
    };
    let resolved = sv_resolve_dendrogram(tree, axis, order);
    let geometry = sv_dendrogram_geometry(&resolved, labels.len(), plot, style);
    geometries.push(geometry);
    Some(resolved)
}

fn sv_dendrogram_geometry(
    dendrogram: &SVDendrogram,
    number_of_leaves: usize,
    plot: SVResolvedRectangle,
    style: &SVDecorationStyle,
) -> SVMarkGeometry<'static> {
    let (region, reverse_distance) = match dendrogram.axis() {
        SVClusterAxis::Row => (
            SVResolvedRectangle::new(
                plot.x - 12.0 - SV_CLUSTERED_ROW_DENDROGRAM_WIDTH,
                plot.y,
                SV_CLUSTERED_ROW_DENDROGRAM_WIDTH,
                plot.height,
            ),
            true,
        ),
        SVClusterAxis::Column => (
            SVResolvedRectangle::new(
                plot.x,
                plot.y - 12.0 - SV_CLUSTERED_COLUMN_DENDROGRAM_HEIGHT,
                plot.width,
                SV_CLUSTERED_COLUMN_DENDROGRAM_HEIGHT,
            ),
            false,
        ),
    };
    let maximum = if dendrogram.maximum_distance() > 0.0 {
        dendrogram.maximum_distance()
    } else {
        1.0
    };
    let number_of_leaves = number_of_leaves.max(1);

    let mut primitives = Vec::with_capacity(dendrogram.number_of_merges());
    for merge in dendrogram.merges() {
        let left_leaf = merge.left_position() * number_of_leaves as f64 - 0.5;
        let right_leaf = merge.right_position() * number_of_leaves as f64 - 0.5;
        let commands = match dendrogram.axis() {
            SVClusterAxis::Row => {
                let x = |distance: f64| {
                    let fraction = distance / maximum;
                    if reverse_distance {
                        region.right() - fraction * region.width
                    } else {
                        region.x + fraction * region.width
                    }
                };
                let y =
                    |leaf: f64| region.y + (leaf + 0.5) / number_of_leaves as f64 * region.height;
                vec![
                    SVPathCommand::MoveTo(SVMarkPoint::new(x(merge.left_distance()), y(left_leaf))),
                    SVPathCommand::LineTo(SVMarkPoint::new(x(merge.distance()), y(left_leaf))),
                    SVPathCommand::LineTo(SVMarkPoint::new(x(merge.distance()), y(right_leaf))),
                    SVPathCommand::LineTo(SVMarkPoint::new(
                        x(merge.right_distance()),
                        y(right_leaf),
                    )),
                ]
            }
            SVClusterAxis::Column => {
                let y = |distance: f64| {
                    let fraction = distance / maximum;
                    region.bottom() - fraction * region.height
                };
                let x =
                    |leaf: f64| region.x + (leaf + 0.5) / number_of_leaves as f64 * region.width;
                vec![
                    SVPathCommand::MoveTo(SVMarkPoint::new(x(left_leaf), y(merge.left_distance()))),
                    SVPathCommand::LineTo(SVMarkPoint::new(x(left_leaf), y(merge.distance()))),
                    SVPathCommand::LineTo(SVMarkPoint::new(x(right_leaf), y(merge.distance()))),
                    SVPathCommand::LineTo(SVMarkPoint::new(
                        x(right_leaf),
                        y(merge.right_distance()),
                    )),
                ]
            }
        };
        primitives.push(SVMarkPrimitive::new(
            SVMarkShape::Path(SVGeometryPath::new(commands)),
            SVMarkPaint::stroked(style.axis(), 1.5),
        ));
    }
    SVMarkGeometry::new(primitives)
}
