//! One joint render: resolve, compose the three panels, assemble the scene.

use super::super::configuration::SVJointConfiguration;
use super::super::scene::SVJointScene;
use super::central::sv_compose_central;
use super::data::sv_resolve_columns;
use super::decorations::sv_joint_decorations;
use super::layout::sv_solve_panels;
use super::marginals::sv_compose_marginals;
use crate::sv_data::SVColumnSnapshot;
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;

pub(crate) fn sv_compose_scene(
    configuration: &SVJointConfiguration<'_>,
) -> Result<SVJointScene, SVError> {
    let panels = sv_solve_panels()?;
    let mut horizontal_snapshot: SVColumnSnapshot<'_> =
        configuration.data_source.column(&configuration.x)?;
    let mut vertical_snapshot = configuration.data_source.column(&configuration.y)?;
    let mut series_snapshot = match configuration.series.as_deref() {
        Some(name) => Some(configuration.data_source.column(name)?),
        None => None,
    };

    let columns = sv_resolve_columns(
        horizontal_snapshot.column_view(),
        vertical_snapshot.column_view(),
        series_snapshot.as_mut().map(SVColumnSnapshot::column_view),
        configuration.missing_value_policy,
        &configuration.x,
        &configuration.y,
    )?;

    let central = sv_compose_central(configuration, &columns, panels.central)?;
    let marginal_kind = configuration.marginal_kind.resolve(configuration.kind);
    let mut geometries = central.geometries;
    geometries.extend(sv_compose_marginals(
        &columns,
        marginal_kind,
        central.horizontal_domain,
        central.vertical_domain,
        panels.horizontal_marginal,
        panels.vertical_marginal,
    )?);

    let horizontal_scale = super::central::sv_scale(
        central.horizontal_domain,
        panels.central.x,
        panels.central.right(),
    )?;
    let vertical_scale = super::central::sv_scale(
        central.vertical_domain,
        panels.central.bottom(),
        panels.central.y,
    )?;

    let (before_marks, after_marks) = sv_joint_decorations(
        &horizontal_scale,
        &vertical_scale,
        configuration,
        panels.central,
        panels.horizontal_marginal,
        panels.vertical_marginal,
        panels.viewport,
        &columns.groups,
    )?;

    let number_of_marks = geometries
        .iter()
        .map(crate::sv_mark::SVMarkGeometry::len)
        .sum();

    Ok(SVJointScene {
        backend_kind: configuration.backend_kind,
        viewport: panels.viewport,
        central_panel: panels.central,
        horizontal_marginal_panel: panels.horizontal_marginal,
        vertical_marginal_panel: panels.vertical_marginal,
        background: SVDecorationStyle::built_in().background(),
        title: configuration.title.clone(),
        description: Some("Joint plot generated by scienceview".to_string()),
        horizontal_scale,
        vertical_scale,
        decoration_primitives_before_marks: before_marks,
        mark_geometries: geometries,
        decoration_primitives_after_marks: after_marks,
        legend_labels: columns.series_labels.clone(),
        number_of_series: columns.number_of_series,
        number_of_marks,
        kind: configuration.kind,
        marginal_kind,
    })
}
