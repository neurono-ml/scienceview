//! One render: resolve the variables, solve the grid and compose every cell.

use super::configuration::SVPairConfiguration;
use super::decorations::sv_grid_decorations;
use super::diagonal::sv_diagonal_geometries;
use super::layout::sv_solve_grid;
use super::off_diagonal::sv_off_diagonal_geometries;
use super::preparation::{sv_cell_points, sv_hue_groups, sv_variable_domains};
use super::scene::SVPairScene;
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_mark::SVMarkGeometry;

pub(super) fn sv_compose_scene(
    configuration: &SVPairConfiguration<'_>,
) -> Result<SVPairScene, SVError> {
    let domains = sv_variable_domains(configuration)?;
    let groups = sv_hue_groups(configuration)?;
    let grid = sv_solve_grid(
        configuration.y_variables.len(),
        configuration.x_variables.len(),
    );

    let (before_marks, after_marks) =
        sv_grid_decorations(configuration, grid.viewport, &grid.cells, &domains, &groups);

    let horizontal_domain = sv_domain(&domains, &configuration.x_variables)?;
    let vertical_domain = sv_domain(&domains, &configuration.y_variables)?;
    let mut mark_geometries: Vec<SVMarkGeometry<'static>> = Vec::new();
    let mut number_of_marks = 0;

    for (row, y_name) in configuration.y_variables.iter().enumerate() {
        for (column, x_name) in configuration.x_variables.iter().enumerate() {
            let cell = grid.cells[row][column];
            let is_diagonal = row == column && x_name == y_name;
            let (geometries, count) = if is_diagonal {
                sv_diagonal_geometries(
                    configuration,
                    x_name,
                    cell,
                    horizontal_domain[column],
                    &groups,
                )?
            } else {
                let points = sv_cell_points(configuration, x_name, y_name, &groups)?;
                sv_off_diagonal_geometries(
                    configuration,
                    &points,
                    cell,
                    horizontal_domain[column],
                    vertical_domain[row],
                    &groups,
                )?
            };
            mark_geometries.extend(geometries);
            number_of_marks += count;
        }
    }

    Ok(SVPairScene {
        backend_kind: configuration.backend_kind,
        viewport: grid.viewport,
        plot_area: grid.grid_area,
        background: SVDecorationStyle::built_in().background(),
        title: configuration.title.clone(),
        description: Some("Pair plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries,
        decoration_primitives_after_marks: after_marks,
        cell_rectangles: grid.cells.into_iter().flatten().collect(),
        number_of_series: groups.groups.len(),
        number_of_marks,
    })
}

fn sv_domain(
    domains: &std::collections::BTreeMap<String, super::preparation::SVPairDomain>,
    variables: &[String],
) -> Result<Vec<super::preparation::SVPairDomain>, SVError> {
    variables
        .iter()
        .map(|name| {
            domains
                .get(name)
                .copied()
                .ok_or_else(|| sv_missing_domain(name))
        })
        .collect()
}

fn sv_missing_domain(name: &str) -> SVError {
    SVError::InvalidConfiguration {
        message: format!("the pair grid did not resolve a domain for `{name}`"),
    }
}
