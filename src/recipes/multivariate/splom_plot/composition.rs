//! One render: resolve the variables, solve the grid and compose every cell.
//!
//! The composition is the recipe of FDR-143: the observations are shared across
//! the cells, every off-diagonal cell is a scatter of two variables through
//! `SVMark::Dot`, every diagonal cell is a univariate distribution through
//! `SVStat::Bin` or `SVStat::KernelDensity`, and the grid geometry comes from
//! `sv_layout`. No kernel variant is added and no position is re-derived by a
//! serializer.

use super::SVSplomCellKind;
use super::configuration::SVSplomConfiguration;
use super::decorations::sv_splom_decorations;
use super::diagonal::sv_diagonal_geometry;
use super::geometry::sv_paint_points;
use super::matrix::sv_solve_grid;
use super::preparation::{SVSplomPreparedData, sv_prepare_data};
use super::scene::{SVSplomCell, SVSplomScene};
use crate::sv_data::{SVColumnSnapshot, SVColumnView};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::SVResolvedRectangle;
use crate::sv_mark::{SVMark, SVMarkGeometry, SVMarkRequest, SVMarkTheme};
use crate::sv_scale::{SVColour, SVScaleBuilder, SVScaleKind};

pub(super) fn sv_compose_scene(
    configuration: &SVSplomConfiguration<'_>,
) -> Result<SVSplomScene, SVError> {
    let number_of_variables = configuration.variables.len();
    let mut snapshots = sv_variable_snapshots(configuration)?;
    let mut colour_snapshot = match configuration.colour.as_deref() {
        Some(name) => Some(configuration.data_source.column(name)?),
        None => None,
    };

    let views: Vec<SVColumnView<'_>> = snapshots
        .iter_mut()
        .map(SVColumnSnapshot::column_view)
        .collect();
    let colour_view = colour_snapshot.as_mut().map(SVColumnSnapshot::column_view);
    let prepared = sv_prepare_data(configuration, &views, colour_view)?;
    let grid = sv_solve_grid(number_of_variables, configuration.cell_aspect)?;

    let theme = SVMarkTheme::default();
    let point_colours = sv_point_colours(&prepared);
    let mut cells = Vec::new();
    let mut geometries = Vec::new();
    let mut number_of_marks = 0;

    for row in 0..number_of_variables {
        for column in 0..number_of_variables {
            let rectangle = grid
                .cell(row, column)
                .map(|cell| cell.rectangle)
                .ok_or_else(|| SVError::InvalidConfiguration {
                    message: format!("the layout solver did not place cell ({row}, {column})"),
                })?;
            let (kind, geometry) = if row == column {
                if !configuration.show_diagonal {
                    continue;
                }
                (
                    SVSplomCellKind::Diagonal,
                    sv_diagonal_geometry(
                        configuration,
                        &prepared.columns[column],
                        prepared.domains[column],
                        rectangle,
                    )?,
                )
            } else {
                let visible = if row < column {
                    configuration.show_upper
                } else {
                    configuration.show_lower
                };
                if !visible {
                    continue;
                }
                number_of_marks += prepared.number_of_observations;
                (
                    SVSplomCellKind::Scatter,
                    sv_scatter_geometry(
                        configuration,
                        &prepared,
                        &point_colours,
                        row,
                        column,
                        rectangle,
                        theme.mark_colour(),
                    )?,
                )
            };
            cells.push(SVSplomCell::new(row, column, rectangle, kind));
            geometries.push(geometry);
        }
    }

    let style = SVDecorationStyle::built_in();
    let (before_marks, after_marks) = sv_splom_decorations(
        configuration,
        &cells,
        |row, column| grid.cell(row, column).map(|cell| cell.rectangle),
        grid.viewport,
        &prepared.groups,
        &style,
    );
    let (legend_labels, legend_colours) = sv_legend_entries(configuration, &prepared);

    Ok(SVSplomScene {
        backend_kind: configuration.backend_kind,
        viewport: grid.viewport,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some("Scatterplot matrix generated by scienceview".to_string()),
        cells,
        decoration_primitives_before_marks: before_marks,
        mark_geometries: geometries,
        decoration_primitives_after_marks: after_marks,
        number_of_variables,
        number_of_observations: prepared.number_of_observations,
        number_of_marks,
        legend_labels,
        legend_colours,
    })
}

fn sv_variable_snapshots<'configuration>(
    configuration: &'configuration SVSplomConfiguration<'_>,
) -> Result<Vec<SVColumnSnapshot<'configuration>>, SVError> {
    configuration
        .variables
        .iter()
        .map(|name| configuration.data_source.column(name))
        .collect()
}

fn sv_scatter_geometry(
    configuration: &SVSplomConfiguration<'_>,
    prepared: &SVSplomPreparedData<'_>,
    point_colours: &[SVColour],
    row: usize,
    column: usize,
    rectangle: SVResolvedRectangle,
    default_colour: SVColour,
) -> Result<SVMarkGeometry<'static>, SVError> {
    let horizontal_domain = prepared.domains[column];
    let vertical_domain = prepared.domains[row];
    let horizontal = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(horizontal_domain.0, horizontal_domain.1)
        .range(rectangle.x, rectangle.right())
        .build()?;
    let vertical = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(vertical_domain.0, vertical_domain.1)
        .range(rectangle.bottom(), rectangle.y)
        .build()?;

    let mark: SVMark = SVMark::dot()
        .shape(configuration.marker)
        .size(configuration.size)
        .into();
    let horizontal_values = prepared.columns[column].view();
    let vertical_values = prepared.columns[row].view();
    let request = SVMarkRequest::new(
        horizontal_values,
        vertical_values,
        &horizontal,
        &vertical,
        rectangle,
    );
    let geometry = mark.geometry(&request)?;
    let primitives = sv_paint_points(
        geometry,
        point_colours,
        default_colour,
        configuration.opacity,
    )?;
    Ok(SVMarkGeometry::new(primitives))
}

fn sv_point_colours(prepared: &SVSplomPreparedData<'_>) -> Vec<SVColour> {
    prepared
        .group_indices
        .iter()
        .filter_map(|index| prepared.groups.get(*index).map(|group| group.colour))
        .collect()
}

fn sv_legend_entries(
    configuration: &SVSplomConfiguration<'_>,
    prepared: &SVSplomPreparedData<'_>,
) -> (Vec<String>, Vec<SVColour>) {
    if configuration.colour.is_none() {
        return (Vec::new(), Vec::new());
    }
    prepared
        .groups
        .iter()
        .map(|group| (group.label.clone(), group.colour))
        .unzip()
}
