//! Serializing the composition through the backend that produced it.

use super::SVParallelCoordinatesRenderOutput;
#[cfg(any(feature = "render-svg", feature = "render-native"))]
use crate::sv_backend::{SVBackendCapability, SVBackendKind};
#[cfg(any(feature = "render-svg", feature = "render-native"))]
use crate::sv_error::SVError;

impl SVParallelCoordinatesRenderOutput {
    /// Serializes the composition as a self-contained SVG document.
    ///
    /// # Errors
    ///
    /// Returns [`SVError::UnsupportedBackendCapability`] when the figure was
    /// configured for a kind other than `Svg`.
    #[cfg(feature = "render-svg")]
    pub fn to_svg(&self) -> Result<String, SVError> {
        if self.backend_kind() != SVBackendKind::Svg {
            return Err(SVError::UnsupportedBackendCapability {
                backend_kind: self.backend_kind(),
                capability: SVBackendCapability::Export,
            });
        }
        let mut document = scienceview_svg::SVSvgDocument::new(self.viewport())
            .with_title(
                self.title()
                    .unwrap_or("parallel coordinates plot")
                    .to_string(),
            )
            .with_description("Parallel coordinates generated by scienceview")
            .with_background(self.background());
        for geometry in self.geometries() {
            document.push_mark_geometry(geometry);
        }
        document.push_decoration_primitives(self.decorations());
        Ok(document.to_svg())
    }

    /// Rasterizes the composition with the from-scratch native renderer.
    ///
    /// # Errors
    ///
    /// Returns [`SVError::UnsupportedBackendCapability`] when the figure was
    /// configured for a kind other than `Native`.
    #[cfg(feature = "render-native")]
    pub fn to_native_frame(&self) -> Result<scienceview_native::SVNativeFrame, SVError> {
        if self.backend_kind() != SVBackendKind::Native {
            return Err(SVError::UnsupportedBackendCapability {
                backend_kind: self.backend_kind(),
                capability: SVBackendCapability::Presentation,
            });
        }
        let mut canvas = scienceview_native::SVRasterCanvas::new(&self.viewport());
        canvas.fill(self.background());
        for geometry in self.geometries() {
            canvas.draw_mark_geometry(geometry);
        }
        canvas.draw_decoration_primitives(self.decorations());
        Ok(canvas.to_frame())
    }
}
