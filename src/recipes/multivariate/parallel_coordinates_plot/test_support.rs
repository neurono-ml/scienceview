//! Shared mock data and serialization helpers for the parallel-coordinates tests.

use super::{SVParallelCoordinatesPlot, SVParallelCoordinatesRenderOutput};
use crate::sv_backend::SVBackendKind;
use crate::sv_data::{
    SVColumnSnapshot, SVColumnView, SVDataSource, SVSourceSchema, SVSparseView, SVStreamingView,
};
use crate::sv_error::SVError;

pub(crate) const FIRST: [f64; 4] = [1.0, 2.0, 3.0, 4.0];
pub(crate) const SECOND: [f64; 4] = [10.0, 20.0, 30.0, 40.0];
pub(crate) const THIRD: [f64; 4] = [0.0, 1.0, 0.0, 1.0];
pub(crate) const GROUP: [f64; 4] = [0.0, 0.0, 1.0, 1.0];
pub(crate) const VARIABLES: [&str; 3] = ["first", "second", "third"];

/// A synthetic source serving every representation through one seam.
pub(crate) struct SVTestSource<'a> {
    pub(crate) first: SVColumnView<'a>,
    pub(crate) second: SVColumnView<'a>,
    pub(crate) third: SVColumnView<'a>,
    pub(crate) group: SVColumnView<'a>,
}

impl SVDataSource for SVTestSource<'_> {
    fn schema(&self) -> SVSourceSchema<'_> {
        unreachable!("the parallel-coordinates recipe resolves columns by name")
    }

    fn column(&self, name: &str) -> Result<SVColumnSnapshot<'_>, SVError> {
        let view = match name {
            "first" => self.first,
            "second" => self.second,
            "third" => self.third,
            "group" => self.group,
            _ => {
                return Err(SVError::ColumnNotFound {
                    name: name.to_string(),
                });
            }
        };
        Ok(SVColumnSnapshot::Borrowed(view))
    }
}

pub(crate) fn sv_dense_source() -> SVTestSource<'static> {
    SVTestSource {
        first: SVColumnView::Dense(&FIRST),
        second: SVColumnView::Dense(&SECOND),
        third: SVColumnView::Dense(&THIRD),
        group: SVColumnView::Dense(&GROUP),
    }
}

pub(crate) fn sv_sparse_source() -> SVTestSource<'static> {
    const INDICES: [usize; 4] = [0, 1, 2, 3];
    let first = SVSparseView::new(&INDICES, &FIRST, 4).expect("the sparse view is well formed");
    let second = SVSparseView::new(&INDICES, &SECOND, 4).expect("the sparse view is well formed");
    let third = SVSparseView::new(&INDICES, &THIRD, 4).expect("the sparse view is well formed");
    let group = SVSparseView::new(&INDICES, &GROUP, 4).expect("the sparse view is well formed");
    SVTestSource {
        first: SVColumnView::Sparse(first),
        second: SVColumnView::Sparse(second),
        third: SVColumnView::Sparse(third),
        group: SVColumnView::Sparse(group),
    }
}

pub(crate) fn sv_streaming_source() -> SVTestSource<'static> {
    SVTestSource {
        first: SVColumnView::Streaming(SVStreamingView::new(&FIRST, 4, 0)),
        second: SVColumnView::Streaming(SVStreamingView::new(&SECOND, 4, 0)),
        third: SVColumnView::Streaming(SVStreamingView::new(&THIRD, 4, 0)),
        group: SVColumnView::Streaming(SVStreamingView::new(&GROUP, 4, 0)),
    }
}

pub(crate) fn sv_partially_sparse_source() -> SVTestSource<'static> {
    const INDICES: [usize; 2] = [0, 2];
    const STORED: [f64; 2] = [10.0, 30.0];
    let second = SVSparseView::new(&INDICES, &STORED, 4).expect("the sparse view is well formed");
    SVTestSource {
        first: SVColumnView::Dense(&FIRST),
        second: SVColumnView::Sparse(second),
        third: SVColumnView::Dense(&THIRD),
        group: SVColumnView::Dense(&GROUP),
    }
}

/// A source whose middle variable carries a non-finite observation.
pub(crate) fn sv_missing_source() -> SVTestSource<'static> {
    const MISSING_SECOND: [f64; 4] = [10.0, f64::NAN, 30.0, 40.0];
    SVTestSource {
        first: SVColumnView::Dense(&FIRST),
        second: SVColumnView::Dense(&MISSING_SECOND),
        third: SVColumnView::Dense(&THIRD),
        group: SVColumnView::Dense(&GROUP),
    }
}

pub(crate) fn sv_build_default<'a>(source: &'a SVTestSource<'a>) -> SVParallelCoordinatesPlot<'a> {
    SVParallelCoordinatesPlot::builder()
        .data_source(source)
        .variables(&VARIABLES)
        .backend(SVBackendKind::Svg)
        .build()
        .expect("the default configuration is complete")
}

pub(crate) fn sv_output_svg(output: &SVParallelCoordinatesRenderOutput) -> String {
    let mut document = scienceview_svg::SVSvgDocument::new(output.viewport())
        .with_title(output.title().unwrap_or("parallel coordinates"))
        .with_description("Parallel coordinates generated by scienceview")
        .with_background(output.background());
    for geometry in output.geometries() {
        document.push_mark_geometry(geometry);
    }
    document.push_decoration_primitives(output.decorations());
    document.to_svg()
}
