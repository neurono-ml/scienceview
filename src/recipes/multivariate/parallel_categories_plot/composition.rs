//! One render: resolve the ribbons, derive the scales and compose the scene.

use super::configuration::{
    SV_PARALLEL_CATEGORIES_PLOT_HEIGHT, SV_PARALLEL_CATEGORIES_PLOT_LEFT,
    SV_PARALLEL_CATEGORIES_PLOT_TOP, SV_PARALLEL_CATEGORIES_PLOT_WIDTH,
    SV_PARALLEL_CATEGORIES_VIEWPORT_HEIGHT, SV_PARALLEL_CATEGORIES_VIEWPORT_WIDTH,
    SVParallelCategoriesConfiguration,
};
use super::decorations::sv_parallel_categories_decorations;
use super::geometry::sv_compose_ribbon_geometries;
use super::preparation::{SVPreparedParallelCategories, sv_prepare};
use super::scene::{
    SVParallelCategoriesAxis, SVParallelCategoriesRibbon, SVParallelCategoriesScene,
};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};
use crate::sv_scale::{SVScaleBuilder, SVScaleKind};

pub(super) fn sv_compose_scene(
    configuration: &SVParallelCategoriesConfiguration<'_>,
) -> Result<SVParallelCategoriesScene, SVError> {
    let viewport = SVViewport::new(
        SV_PARALLEL_CATEGORIES_VIEWPORT_WIDTH,
        SV_PARALLEL_CATEGORIES_VIEWPORT_HEIGHT,
    );
    let plot = SVResolvedRectangle::new(
        SV_PARALLEL_CATEGORIES_PLOT_LEFT,
        SV_PARALLEL_CATEGORIES_PLOT_TOP,
        SV_PARALLEL_CATEGORIES_PLOT_WIDTH,
        SV_PARALLEL_CATEGORIES_PLOT_HEIGHT,
    );
    let prepared = sv_prepare(configuration)?;

    let number_of_axes = prepared.axes.len().max(1) as f64;
    let horizontal = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(-0.5, number_of_axes - 0.5)
        .range(plot.x, plot.right())
        .build()?;
    let vertical = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(0.0, 1.0)
        .range(plot.bottom(), plot.y)
        .build()?;

    let geometries =
        sv_compose_ribbon_geometries(&prepared, configuration, &horizontal, &vertical, plot)?;
    let (before_marks, after_marks) =
        sv_parallel_categories_decorations(configuration, &prepared, plot, viewport)?;

    Ok(SVParallelCategoriesScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: SVDecorationStyle::built_in().background(),
        title: configuration.title.clone(),
        description: Some("Parallel categories plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries: geometries,
        decoration_primitives_after_marks: after_marks,
        axes: sv_axis_summaries(&prepared),
        ribbons: sv_ribbon_summaries(&prepared),
        number_of_observations: prepared.number_of_observations,
    })
}

fn sv_axis_summaries(prepared: &SVPreparedParallelCategories) -> Vec<SVParallelCategoriesAxis> {
    prepared
        .axes
        .iter()
        .map(|axis| SVParallelCategoriesAxis {
            name: axis.name.clone(),
            label: axis.label.clone(),
            categories: axis.categories.clone(),
            category_labels: axis.category_labels.clone(),
        })
        .collect()
}

fn sv_ribbon_summaries(prepared: &SVPreparedParallelCategories) -> Vec<SVParallelCategoriesRibbon> {
    prepared
        .ribbons
        .iter()
        .map(|ribbon| {
            let left_variable = prepared
                .axes
                .get(ribbon.left_axis)
                .map_or_else(String::new, |axis| axis.name.clone());
            let right_variable = prepared
                .axes
                .get(ribbon.right_axis)
                .map_or_else(String::new, |axis| axis.name.clone());
            let left_category = prepared
                .axes
                .get(ribbon.left_axis)
                .and_then(|axis| axis.categories.get(ribbon.left_category))
                .copied()
                .unwrap_or(0.0);
            let right_category = prepared
                .axes
                .get(ribbon.right_axis)
                .and_then(|axis| axis.categories.get(ribbon.right_category))
                .copied()
                .unwrap_or(0.0);
            SVParallelCategoriesRibbon {
                left_variable,
                right_variable,
                left_category,
                right_category,
                count: ribbon.count,
                colour: ribbon.colour,
            }
        })
        .collect()
}
