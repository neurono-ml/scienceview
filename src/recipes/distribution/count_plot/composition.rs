//! One render: resolve the counts, derive the scales and compose the scene.

use super::configuration::{
    SV_COUNT_PLOT_HEIGHT, SV_COUNT_PLOT_LEFT, SV_COUNT_PLOT_TOP, SV_COUNT_PLOT_WIDTH,
    SV_COUNT_VIEWPORT_HEIGHT, SV_COUNT_VIEWPORT_WIDTH, SVCountConfiguration,
};
use super::decorations::sv_count_decorations;
use super::geometry::{sv_domains, sv_series_primitives};
use super::preparation::{SVPreparedCount, sv_prepare};
use super::scene::{SVCountScene, SVCountSeriesSummary};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};
use crate::sv_mark::{SVBarOrientation, SVMarkGeometry, SVMarkTheme};
use crate::sv_scale::{SVScale, SVScaleBuilder, SVScaleKind};

pub(super) fn sv_compose_scene(
    configuration: &SVCountConfiguration<'_>,
) -> Result<SVCountScene, SVError> {
    let viewport = SVViewport::new(SV_COUNT_VIEWPORT_WIDTH, SV_COUNT_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_COUNT_PLOT_LEFT,
        SV_COUNT_PLOT_TOP,
        SV_COUNT_PLOT_WIDTH,
        SV_COUNT_PLOT_HEIGHT,
    );
    let prepared = sv_prepare(configuration)?;
    let domains = sv_domains(&prepared);

    let category_range = match configuration.orientation {
        SVBarOrientation::Vertical => (plot.x, plot.right()),
        SVBarOrientation::Horizontal => (plot.bottom(), plot.y),
    };
    let value_range = match configuration.orientation {
        SVBarOrientation::Vertical => (plot.bottom(), plot.y),
        SVBarOrientation::Horizontal => (plot.x, plot.right()),
    };
    let category = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domains.category_low, domains.category_high)
        .range(category_range.0, category_range.1)
        .build()?;
    let value = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domains.value_low, domains.value_high)
        .range(value_range.0, value_range.1)
        .build()?;
    let relative_value = sv_relative_value_scale(&value, plot.height, 0.0)?;

    let labels = sv_category_labels(configuration, &prepared);
    let label_references: Vec<&str> = labels.iter().map(String::as_str).collect();
    let nominal = sv_nominal_scale(configuration, &label_references, plot)?;
    let (bottom_axis_scale, left_axis_scale) = match configuration.orientation {
        SVBarOrientation::Vertical => (&nominal, &relative_value),
        SVBarOrientation::Horizontal => (&relative_value, &nominal),
    };

    let theme = SVMarkTheme::default();
    let mut geometries = Vec::with_capacity(prepared.series.len());
    let mut summaries = Vec::with_capacity(prepared.series.len());
    for series in &prepared.series {
        let primitives = sv_series_primitives(
            configuration,
            series,
            prepared.series.len(),
            plot,
            &category,
            &value,
            &theme,
        )?;
        geometries.push(SVMarkGeometry::new(primitives));
        summaries.push(SVCountSeriesSummary::new(
            series.label.clone(),
            series.colour,
            series.counts.clone(),
        ));
    }

    let totals = sv_totals(&prepared);
    let (before_marks, after_marks) = sv_count_decorations(
        configuration,
        &prepared,
        bottom_axis_scale,
        left_axis_scale,
        plot,
        viewport,
        &labels,
    );

    Ok(SVCountScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: SVDecorationStyle::built_in().background(),
        title: configuration.title.clone(),
        description: Some("Count plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries: geometries,
        decoration_primitives_after_marks: after_marks,
        categories: prepared.categories.clone(),
        category_labels: labels,
        totals,
        series: summaries,
        number_of_bars: prepared.number_of_bars(),
    })
}

fn sv_nominal_scale<'labels>(
    configuration: &SVCountConfiguration<'_>,
    labels: &'labels [&'labels str],
    plot: SVResolvedRectangle,
) -> Result<SVScale<'labels>, SVError> {
    let count = labels.len().max(1) as f64;
    let (start, end) = match configuration.orientation {
        SVBarOrientation::Vertical => {
            let inset = plot.width / (2.0 * count);
            (inset, plot.width - inset)
        }
        SVBarOrientation::Horizontal => {
            let inset = plot.height / (2.0 * count);
            (plot.height - inset, inset)
        }
    };
    SVScaleBuilder::new(SVScaleKind::Nominal)
        .categories(labels)
        .range(start, end)
        .build()
}

fn sv_totals(prepared: &SVPreparedCount) -> Vec<f64> {
    let mut totals = vec![0.0f64; prepared.categories.len()];
    for series in &prepared.series {
        for (total, count) in totals.iter_mut().zip(series.counts.iter()) {
            *total += *count;
        }
    }
    totals
}

fn sv_category_labels(
    configuration: &SVCountConfiguration<'_>,
    prepared: &SVPreparedCount,
) -> Vec<String> {
    prepared
        .categories
        .iter()
        .enumerate()
        .map(|(index, code)| {
            configuration
                .category_labels
                .get(index)
                .cloned()
                .unwrap_or_else(|| sv_category_label(*code))
        })
        .collect()
}

fn sv_category_label(code: f64) -> String {
    if code.fract() == 0.0 {
        format!("category {}", code as i64)
    } else {
        format!("category {code}")
    }
}

fn sv_relative_value_scale(
    scale: &SVScale<'_>,
    start: f64,
    end: f64,
) -> Result<SVScale<'static>, SVError> {
    let domain = scale.domain();
    SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domain.lower(), domain.upper())
        .range(start, end)
        .build()
}
