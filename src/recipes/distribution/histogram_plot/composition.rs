//! One render: resolve the bins, derive the scales and compose the scene.

use super::configuration::{
    SV_HISTOGRAM_PLOT_HEIGHT, SV_HISTOGRAM_PLOT_LEFT, SV_HISTOGRAM_PLOT_TOP,
    SV_HISTOGRAM_PLOT_WIDTH, SV_HISTOGRAM_VIEWPORT_HEIGHT, SV_HISTOGRAM_VIEWPORT_WIDTH,
    SVHistogramConfiguration,
};
use super::decorations::sv_histogram_decorations;
use super::geometry::{sv_domains, sv_series_primitives};
use super::preparation::sv_prepare;
use super::scene::{SVHistogramScene, SVHistogramSeriesSummary};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};
use crate::sv_mark::{SVBarOrientation, SVMarkGeometry, SVMarkTheme};
use crate::sv_scale::{SVScale, SVScaleBuilder, SVScaleKind};

pub(super) fn sv_compose_scene(
    configuration: &SVHistogramConfiguration<'_>,
) -> Result<SVHistogramScene, SVError> {
    let viewport = SVViewport::new(SV_HISTOGRAM_VIEWPORT_WIDTH, SV_HISTOGRAM_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_HISTOGRAM_PLOT_LEFT,
        SV_HISTOGRAM_PLOT_TOP,
        SV_HISTOGRAM_PLOT_WIDTH,
        SV_HISTOGRAM_PLOT_HEIGHT,
    );
    let plot_extent = match configuration.orientation {
        SVBarOrientation::Vertical => plot.width,
        SVBarOrientation::Horizontal => plot.height,
    };
    let prepared = sv_prepare(configuration, plot_extent)?;
    let domains = sv_domains(configuration, &prepared);

    let horizontal = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domains.horizontal_low, domains.horizontal_high)
        .range(plot.x, plot.right())
        .build()?;
    let vertical = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domains.vertical_low, domains.vertical_high)
        .range(plot.bottom(), plot.y)
        .build()?;
    let horizontal_axis = sv_relative_scale(&horizontal, 0.0, plot.width)?;
    let vertical_axis = sv_relative_scale(&vertical, plot.height, 0.0)?;

    let theme = SVMarkTheme::default();
    let mut geometries = Vec::with_capacity(prepared.series.len());
    let mut summaries = Vec::with_capacity(prepared.series.len());
    for series in &prepared.series {
        let primitives = sv_series_primitives(
            configuration,
            series,
            prepared.series.len(),
            plot,
            &horizontal,
            &vertical,
            &theme,
        )?;
        geometries.push(SVMarkGeometry::new(primitives));
        summaries.push(SVHistogramSeriesSummary::new(
            series.label.clone(),
            series.colour,
            series.edges.clone(),
            series.tops.clone(),
        ));
    }

    let (before_marks, after_marks) = sv_histogram_decorations(
        configuration,
        &prepared,
        &horizontal_axis,
        &vertical_axis,
        plot,
        viewport,
    );

    Ok(SVHistogramScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: SVDecorationStyle::built_in().background(),
        title: configuration.title.clone(),
        description: Some("Histogram plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries: geometries,
        decoration_primitives_after_marks: after_marks,
        series: summaries,
        number_of_bars: prepared.number_of_bars(),
    })
}

fn sv_relative_scale(
    scale: &SVScale<'_>,
    start: f64,
    end: f64,
) -> Result<SVScale<'static>, SVError> {
    let domain = scale.domain();
    SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domain.lower(), domain.upper())
        .range(start, end)
        .build()
}
