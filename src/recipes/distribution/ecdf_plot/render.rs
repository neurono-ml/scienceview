//! Serializing the composition through the real backends.
//!
//! `Svg` and `Native` write the very same primitives in the very same order;
//! the native frame differs only by rasterization (FDR-114 backend notes).

use super::composition::SVEcdfPlotComposition;
#[cfg(any(feature = "render-svg", feature = "render-native"))]
use scienceview_core::sv_backend::SVBackendKind;
#[cfg(any(feature = "render-svg", feature = "render-native"))]
use scienceview_core::sv_error::SVError;

impl SVEcdfPlotComposition {
    /// Serializes the composition as one self-contained SVG document.
    ///
    /// # Errors
    ///
    /// Returns [`SVError::InvalidConfiguration`] when the figure was configured
    /// for a backend other than `Svg`.
    #[cfg(feature = "render-svg")]
    pub fn to_svg(&self) -> Result<String, SVError> {
        if self.backend_kind != SVBackendKind::Svg {
            return Err(sv_wrong_backend(
                "SVG",
                self.backend_kind,
                SVBackendKind::Svg,
            ));
        }
        let mut document = scienceview_svg::SVSvgDocument::new(self.viewport)
            .with_description("ECDF plot generated by scienceview")
            .with_background(self.background);
        if let Some(title) = &self.title {
            document = document.with_title(title.clone());
        }
        document.push_decoration_primitives(&self.decorations_before_marks);
        for geometry in self.mark_geometries()? {
            document.push_mark_geometry(&geometry);
        }
        document.push_decoration_primitives(&self.decorations_after_marks);
        Ok(document.to_svg())
    }

    /// Rasterizes the composition into one native frame.
    ///
    /// The frame is the very geometry the SVG serializer writes: the same mark
    /// primitives and the same decoration primitives, in the same order. A
    /// backend configured for anything else is rejected instead of being
    /// silently rendered as native (patterns P7).
    ///
    /// # Errors
    ///
    /// Returns [`SVError::InvalidConfiguration`] when the figure was configured
    /// for a backend other than `Native`.
    #[cfg(feature = "render-native")]
    pub fn to_native_frame(&self) -> Result<scienceview_native::SVNativeFrame, SVError> {
        if self.backend_kind != SVBackendKind::Native {
            return Err(sv_wrong_backend(
                "native",
                self.backend_kind,
                SVBackendKind::Native,
            ));
        }
        let mut canvas = scienceview_native::SVRasterCanvas::new(&self.viewport);
        canvas.fill(self.background);
        canvas.draw_decoration_primitives(&self.decorations_before_marks);
        for geometry in self.mark_geometries()? {
            canvas.draw_mark_geometry(&geometry);
        }
        canvas.draw_decoration_primitives(&self.decorations_after_marks);
        Ok(canvas.to_frame())
    }
}

/// Builds the error of asking a serializer for the wrong configured backend.
#[cfg(any(feature = "render-svg", feature = "render-native"))]
fn sv_wrong_backend(
    serializer: &str,
    configured: SVBackendKind,
    required: SVBackendKind,
) -> SVError {
    SVError::InvalidConfiguration {
        message: format!(
            "the `{configured}` backend has no {serializer} serializer; this figure was configured for `{configured}`, and the {serializer} serializer requires `{required}`"
        ),
    }
}
