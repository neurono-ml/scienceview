//! One render: resolve the columns, derive the scales, lay out the swarm and
//! compose the scene.

use super::channels::sv_resolve_swarm_data;
use super::configuration::{
    SV_SWARM_PLOT_HEIGHT, SV_SWARM_PLOT_LEFT, SV_SWARM_PLOT_TOP, SV_SWARM_PLOT_WIDTH,
    SV_SWARM_VIEWPORT_HEIGHT, SV_SWARM_VIEWPORT_WIDTH, SVSwarmConfiguration,
};
use super::decorations::sv_swarm_decorations;
use super::marks::{SVSwarmMarkInput, sv_compose_mark_geometry};
use super::scales::{sv_build_scales, sv_swarm_width_value};
use super::scene::SVSwarmScene;
use super::swarm_layout::sv_layout_categories;
use crate::sv_data::{SVColumnSnapshot, SVColumnView};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};

pub(super) fn sv_compose_scene(
    configuration: &SVSwarmConfiguration<'_>,
) -> Result<SVSwarmScene, SVError> {
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(SV_SWARM_VIEWPORT_WIDTH, SV_SWARM_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_SWARM_PLOT_LEFT,
        SV_SWARM_PLOT_TOP,
        SV_SWARM_PLOT_WIDTH,
        SV_SWARM_PLOT_HEIGHT,
    );

    let mut value_snapshot = configuration.data_source.column(&configuration.value)?;
    let mut category_snapshot = configuration.data_source.column(&configuration.category)?;
    let mut series_snapshot =
        sv_optional_snapshot(configuration.data_source, configuration.series.as_deref())?;
    let value = value_snapshot.column_view();
    let category = category_snapshot.column_view();
    let series = series_snapshot.as_mut().map(SVColumnSnapshot::column_view);
    sv_check_length("value", value, "category", category)?;
    if let Some(series) = series {
        sv_check_length("value", value, "series", series)?;
    }

    let data = sv_resolve_swarm_data(
        value,
        category,
        series,
        &configuration.series_labels,
        configuration.missing_value_policy,
        &configuration.category,
        configuration.series.as_deref(),
    )?;
    let labels: Vec<String> = data
        .categories
        .iter()
        .map(|category| category.label.clone())
        .collect();
    let label_references: Vec<&str> = labels.iter().map(String::as_str).collect();
    let scales = sv_build_scales(
        &data.observations,
        &label_references,
        configuration.orientation,
        configuration.size,
        plot,
    )?;
    let width_value = sv_swarm_width_value(
        configuration.swarm_width,
        &scales,
        data.categories.len(),
        configuration.orientation,
        plot,
    );
    let category_positions = sv_layout_categories(
        &data.observations,
        scales.marker_extent_value,
        scales.marker_extent_category,
        width_value,
    )?;
    let mark_geometry = sv_compose_mark_geometry(&SVSwarmMarkInput {
        observations: &data.observations,
        category_positions: &category_positions,
        series: &data.series,
        scales: &scales,
        orientation: configuration.orientation,
        marker: configuration.marker,
        alpha: configuration.alpha,
        plot,
    })?;
    let (before_marks, after_marks) =
        sv_swarm_decorations(configuration, &data, &scales, plot, viewport, &style)?;

    let legend_labels = if configuration.series.is_some() {
        data.series
            .iter()
            .map(|series| series.label.clone())
            .collect()
    } else {
        Vec::new()
    };

    Ok(SVSwarmScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some("Swarm plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries: vec![mark_geometry],
        decoration_primitives_after_marks: after_marks,
        legend_labels,
        number_of_series: data.series.len(),
        number_of_marks: data.observations.len(),
        orientation: configuration.orientation,
        category_labels: labels,
    })
}

fn sv_optional_snapshot<'source>(
    data_source: &'source dyn crate::sv_data::SVDataSource,
    name: Option<&str>,
) -> Result<Option<SVColumnSnapshot<'source>>, SVError> {
    match name {
        Some(name) => Ok(Some(data_source.column(name)?)),
        None => Ok(None),
    }
}

fn sv_check_length(
    reference_name: &str,
    reference: SVColumnView<'_>,
    name: &str,
    view: SVColumnView<'_>,
) -> Result<(), SVError> {
    if reference.length() == view.length() {
        return Ok(());
    }
    Err(SVError::MismatchedLengths {
        name: format!("{name} (against {reference_name})"),
        expected: reference.length(),
        actual: view.length(),
    })
}
