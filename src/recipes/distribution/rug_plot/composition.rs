//! One render: resolve the columns, derive the scales and compose the scene.

use super::channels::sv_group_observations;
use super::configuration::{
    SV_RUG_MARGIN, SV_RUG_PLOT_HEIGHT, SV_RUG_PLOT_LEFT, SV_RUG_PLOT_TOP, SV_RUG_PLOT_WIDTH,
    SV_RUG_VIEWPORT_HEIGHT, SV_RUG_VIEWPORT_WIDTH, SVRugConfiguration,
};
use super::decorations::sv_rug_decorations;
use super::geometry::{SVRugGeometryInput, sv_tick_geometries};
use super::scene::SVRugScene;
use crate::sv_data::{SVColumnSnapshot, SVColumnView};
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};
use crate::sv_mark::SVBarOrientation;
use crate::sv_scale::{SVScale, SVScaleBuilder, SVScaleKind};

pub(super) fn sv_compose_scene(
    configuration: &SVRugConfiguration<'_>,
) -> Result<SVRugScene, SVError> {
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(SV_RUG_VIEWPORT_WIDTH, SV_RUG_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_RUG_PLOT_LEFT,
        SV_RUG_PLOT_TOP,
        SV_RUG_PLOT_WIDTH,
        SV_RUG_PLOT_HEIGHT,
    );

    let mut value_snapshot = configuration.data_source.column(&configuration.value)?;
    let mut series_snapshot =
        sv_optional_snapshot(configuration.data_source, configuration.series.as_deref())?;
    let value = value_snapshot.column_view();
    let series = series_snapshot.as_mut().map(SVColumnSnapshot::column_view);

    if let Some(series) = series {
        if series.length() != value.length() {
            return Err(SVError::MismatchedLengths {
                name: "series".to_string(),
                expected: value.length(),
                actual: series.length(),
            });
        }
    }

    let (observations, groups) =
        sv_group_observations(value, series, &configuration.series_labels)?;
    let value_scale = sv_value_scale(value, configuration.orientation, plot)?;
    let axis_scale = sv_relative_axis_scale(&value_scale, configuration.orientation, plot)?;

    let tick_length = f64::from(configuration.height)
        * match configuration.orientation {
            SVBarOrientation::Vertical => plot.height,
            SVBarOrientation::Horizontal => plot.width,
        };
    let (depth_start, depth_end) = match configuration.orientation {
        SVBarOrientation::Vertical => (
            viewport.height() - SV_RUG_MARGIN,
            viewport.height() - SV_RUG_MARGIN - tick_length,
        ),
        SVBarOrientation::Horizontal => (SV_RUG_MARGIN, SV_RUG_MARGIN + tick_length),
    };
    let depth_scale: SVScale<'static> = SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(0.0, 1.0)
        .range(depth_start, depth_end)
        .nice(false)
        .build()?;

    let mark_geometries = sv_tick_geometries(&SVRugGeometryInput {
        observations: &observations,
        groups: &groups,
        value_scale: &value_scale,
        depth_scale: &depth_scale,
        orientation: configuration.orientation,
        plot,
        alpha: configuration.alpha,
        line_width: configuration.line_width,
    })?;

    let (before_marks, after_marks) =
        sv_rug_decorations(&axis_scale, configuration, plot, viewport, &groups, &style);
    let legend_labels: Vec<String> = if configuration.series.is_some() {
        groups.iter().map(|group| group.label.clone()).collect()
    } else {
        Vec::new()
    };

    Ok(SVRugScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some("Rug plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries,
        decoration_primitives_after_marks: after_marks,
        legend_labels,
        number_of_series: groups.len(),
        number_of_marks: observations.len(),
        orientation: configuration.orientation,
    })
}

fn sv_optional_snapshot<'source>(
    data_source: &'source dyn crate::sv_data::SVDataSource,
    name: Option<&str>,
) -> Result<Option<SVColumnSnapshot<'source>>, SVError> {
    match name {
        Some(name) => Ok(Some(data_source.column(name)?)),
        None => Ok(None),
    }
}

fn sv_value_scale(
    view: SVColumnView<'_>,
    orientation: SVBarOrientation,
    plot: SVResolvedRectangle,
) -> Result<SVScale<'_>, SVError> {
    if view.length() == 0 {
        let (start, end) = sv_value_range(orientation, plot);
        return SVScaleBuilder::new(SVScaleKind::Continuous)
            .domain(0.0, 1.0)
            .range(start, end)
            .build();
    }

    let (start, end) = sv_value_range(orientation, plot);
    SVScaleBuilder::new(SVScaleKind::Continuous)
        .data_view(view)
        .range(start, end)
        .build()
}

fn sv_value_range(orientation: SVBarOrientation, plot: SVResolvedRectangle) -> (f64, f64) {
    match orientation {
        SVBarOrientation::Vertical => (plot.x, plot.right()),
        SVBarOrientation::Horizontal => (plot.bottom(), plot.y),
    }
}

fn sv_relative_axis_scale(
    scale: &SVScale<'_>,
    orientation: SVBarOrientation,
    plot: SVResolvedRectangle,
) -> Result<SVScale<'static>, SVError> {
    let domain = scale.domain();
    let (start, end) = match orientation {
        SVBarOrientation::Vertical => (0.0, plot.width),
        SVBarOrientation::Horizontal => (plot.height, 0.0),
    };
    SVScaleBuilder::new(SVScaleKind::Continuous)
        .domain(domain.lower(), domain.upper())
        .range(start, end)
        .build()
}
