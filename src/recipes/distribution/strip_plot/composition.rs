//! One render: resolve the columns, jitter, derive the scales and compose.

use super::configuration::{
    SV_STRIP_PLOT_HEIGHT, SV_STRIP_PLOT_LEFT, SV_STRIP_PLOT_TOP, SV_STRIP_PLOT_WIDTH,
    SV_STRIP_VIEWPORT_HEIGHT, SV_STRIP_VIEWPORT_WIDTH, SVStripConfiguration,
};
use super::data_contract::{SVStripData, sv_resolve_strip_data};
use super::decorations::sv_strip_decorations;
use super::geometry::{SVStripGeometryInput, sv_dot_geometries};
use super::jitter::sv_jittered_categories;
use super::scales::{sv_build_scales, sv_category_labels};
use super::scene::SVStripScene;
use crate::sv_decoration::SVDecorationStyle;
use crate::sv_error::SVError;
use crate::sv_layout::{SVResolvedRectangle, SVViewport};

pub(super) fn sv_compose_scene(
    configuration: &SVStripConfiguration<'_>,
) -> Result<SVStripScene, SVError> {
    let style = SVDecorationStyle::built_in();
    let viewport = SVViewport::new(SV_STRIP_VIEWPORT_WIDTH, SV_STRIP_VIEWPORT_HEIGHT);
    let plot = SVResolvedRectangle::new(
        SV_STRIP_PLOT_LEFT,
        SV_STRIP_PLOT_TOP,
        SV_STRIP_PLOT_WIDTH,
        SV_STRIP_PLOT_HEIGHT,
    );

    let data = sv_resolve_strip_data(configuration)?;
    let displaced_categories = sv_resolve_displaced_categories(configuration, &data)?;

    let mut labels = sv_category_labels(&data.categories);
    if labels.is_empty() {
        labels.push(String::new());
    }
    let label_refs: Vec<&str> = labels.iter().map(String::as_str).collect();
    let scales = sv_build_scales(
        configuration,
        &data.observations,
        &data.categories,
        &label_refs,
        plot,
    )?;

    let mark_geometries = sv_dot_geometries(&SVStripGeometryInput {
        observations: &data.observations,
        groups: &data.groups,
        displaced_categories: &displaced_categories,
        value_scale: &scales.value,
        category_scale: &scales.category,
        plot,
        configuration,
    })?;

    let (before_marks, after_marks) = sv_strip_decorations(
        configuration,
        &scales.value,
        &scales.nominal,
        &data.groups,
        plot,
        viewport,
        &style,
    )?;

    let legend_labels: Vec<String> = if configuration.series.is_some() {
        data.groups
            .iter()
            .map(|group| group.label.clone())
            .collect()
    } else {
        Vec::new()
    };

    Ok(SVStripScene {
        backend_kind: configuration.backend_kind,
        viewport,
        plot_area: plot,
        background: style.background(),
        title: configuration.title.clone(),
        description: Some("Strip plot generated by scienceview".to_string()),
        decoration_primitives_before_marks: before_marks,
        mark_geometries,
        decoration_primitives_after_marks: after_marks,
        legend_labels,
        number_of_series: data.groups.len(),
        number_of_marks: data.observations.len(),
        orientation: configuration.orientation,
    })
}

/// Resolves the category column once more for the jitter kernel.
///
/// The observations already carry their category slot, but the move consumes a
/// column whose length matches the data it displaces; the value column is the
/// one the recipe already resolved.
fn sv_resolve_displaced_categories(
    configuration: &SVStripConfiguration<'_>,
    data: &SVStripData,
) -> Result<Vec<f64>, SVError> {
    let mut value_snapshot = configuration.data_source.column(&configuration.value)?;
    let value = value_snapshot.column_view();
    sv_jittered_categories(value, data, configuration)
}
